LIBRARIES = ("stdlib_stable", "stdlib_upstream_compatible")


@dataclass(frozen=True)
class Configuration:
    name: str
    compiler: Path
    flags: tuple[str, ...]
    ocamllib: Path


@dataclass(frozen=True)
class Toolchain:
    # Either a dune build directory (`_build`) or, if [installed], an
    # installation directory as created by `make install` or `nix build .#oxcaml`.
    root: Path
    installed: bool = False

    def path(self, *, build: str, installed: str) -> Path:
        return self.root / (installed if self.installed else build)

    @property
    def oxfuzzer(self) -> Path:
        return self.path(
            build="main/tools/oxfuzzer/oxfuzzer.exe", installed="bin/oxfuzzer"
        )

    @property
    def ocamlc(self) -> Path:
        return self.path(build="main/main_native.exe", installed="bin/ocamlc.opt")

    @property
    def ocamlopt(self) -> Path:
        return self.path(
            build="main/oxcaml_main_native.exe", installed="bin/ocamlopt.opt"
        )

    @property
    def ocamllib(self) -> Path:
        return self.path(build="default/stdlib/build", installed="lib/ocaml")

    @property
    def ocamlrun(self) -> Path:
        return self.path(build="default/runtime/ocamlrun", installed="bin/ocamlrun")

    def library_dir(self, library: str) -> Path:
        if self.installed:
            return self.ocamllib / library
        return self.root / "main/otherlibs" / library

    # Flags necessary to import libraries required for compilation of programs
    # generated by oxfuzzer.exe. Mirror `libraries` from lib/program.ml.
    def library_flags(self, archive_suffix: str) -> tuple[str, ...]:
        flags: list[str] = []
        for library in LIBRARIES:
            directory = self.library_dir(library)
            if self.installed:
                flags += ["-I", str(directory)]
            else:
                flags += ["-I", str(directory / f".{library}.objs/byte")]
                if archive_suffix == "cmxa":
                    flags += ["-I", str(directory / f".{library}.objs/native")]
        flags += [
            str(self.library_dir(library) / f"{library}.{archive_suffix}")
            for library in LIBRARIES
        ]
        return tuple(flags)

    @property
    def configurations(self) -> tuple[Configuration, ...]:
        return (
            Configuration(
                name="ocamlc",
                compiler=self.ocamlc,
                # Use the runtime from `ocamlrun` created by `make install`.
                flags=(*self.library_flags("cma"), "-use-runtime", str(self.ocamlrun)),
                ocamllib=self.ocamllib,
            ),
            Configuration(
                name="ocamlopt-O4",
                compiler=self.ocamlopt,
                flags=(
                    *self.library_flags("cmxa"),
                    "-O4",
                    "-flambda2-result-types-all-functions",
                    "-flambda2-expert-can-inline-recursive-functions",
                    "-flambda2-match-in-match",
                    "-flambda2-join-algorithm",
                    "n-way",
                    "-experimental-optimizations",
                    "-caml-apply-inline-fast-path",
                ),
                ocamllib=self.ocamllib,
            ),
            # Configuration(
            #     name="ocamlopt-Oclassic",
            #     compiler=self.ocamlopt,
            #     flags=(
            #         *self.library_flags("cmxa"),
            #         "-Oclassic",
            #         "-inline", "0",
            #         "-no-cfg-peephole-optimize",
            #         "-no-cfg-value-propagation",
            #         "-no-cfg-prologue-shrink-wrap",
            #         "-regalloc", "ls",
            #     ),
            #     ocamllib=self.ocamllib,
            # ),
        )

    # Snapshotting is mainly useful for development and running the fuzzer locally.
    # Without copying the toolchain from the compiler repo to another directory, any
    # recompile of oxcaml will cause some compilation failures, while the compiler
    # executable is temporarily nonexistent, for example, which happens fairly often.
    # Installations are not expected to change, so they are used in place.
    def snapshot(self, destination: Path) -> "Toolchain":
        assert not self.installed
        for source in (
            self.oxfuzzer,
            self.ocamlc,
            self.ocamlopt,
            self.ocamlrun,
            self.ocamllib,
            *(self.library_dir(library) for library in LIBRARIES),
        ):
            target = destination / source.relative_to(self.root)
            target.parent.mkdir(parents=True, exist_ok=True)
            if source.is_dir():
                shutil.copytree(source, target)
            else:
                shutil.copy2(source, target)
        return Toolchain(destination)

    # Make sure `make compiler` was run before the fuzzer is executed and that
    # all necessary dependencies are available.
    def check_dependencies(self) -> None:
        missing = [
            path
            for path in [self.oxfuzzer, self.ocamlc, self.ocamlopt, self.ocamlrun]
            if not path.is_file() or not os.access(path, os.X_OK)
        ]
        if not self.ocamllib.is_dir():
            missing.append(self.ocamllib)

        for library in LIBRARIES:
            if not self.library_dir(library).is_dir():
                missing.append(self.library_dir(library))

        if missing:
            formatted = "\n".join(f"  {path}" for path in missing)
            hint = (
                f"Check that {self.root} is an OxCaml installation directory."
                if self.installed
                else "From the repository root, run:\n  make compiler"
            )
            raise SystemExit(f"""oxfuzzer: some dependencies are missing.

Missing files:
{formatted}

{hint}
""")


COMPILE_TIMEOUT_SEC = 100.0
RUN_TIMEOUT_SEC = 10.0
GENERATE_TIMEOUT_SEC = 1.0
MAX_PROGRAM_BYTES = 1024 * 1024

RATE_SMOOTHING = 0.01
PROGRESS_INTERVAL_SEC = 30.0


@dataclass(frozen=True)
class CommandResult:
    returncode: int
    stdout: bytes
    stderr: bytes
    timed_out: bool

    @property
    def ok(self) -> bool:
        return not self.timed_out and self.returncode == 0


def kill_process_group(process: asyncio.subprocess.Process) -> None:
    try:
        os.killpg(process.pid, signal.SIGKILL)
    except (ProcessLookupError, PermissionError):
        # The group is gone. macOS reports a group whose only member is a
        # zombie, exited but not yet waited for, as a permission error.
        pass


# stdout and stderr go to <output_prefix>.stdout and <output_prefix>.stderr
# rather than pipes.
async def run_command(
    command: str,
    args: Sequence[str],
    *,
    cwd: Path | None = None,
    env: dict[str, str] | None = None,
    timeout_sec: float,
    output_prefix: Path,
) -> CommandResult:
    stdout_path = output_prefix.with_suffix(".stdout")
    stderr_path = output_prefix.with_suffix(".stderr")
    with open(stdout_path, "wb") as stdout, open(stderr_path, "wb") as stderr:
        process = await asyncio.create_subprocess_exec(
            command,
            *args,
            cwd=cwd,
            env=None if env is None else {**os.environ, **env},
            stdin=asyncio.subprocess.DEVNULL,
            stdout=stdout,
            stderr=stderr,
            # Start new session, so that we can use killpg to reliably kill the
            # command along with all the children it spawned.
            start_new_session=True,
        )

    timed_out = False
    try:
        async with asyncio.timeout(timeout_sec):
            await process.wait()
    except TimeoutError:
        kill_process_group(process)
        await process.wait()
        timed_out = True
    except asyncio.CancelledError:
        # Cancellation does not stop the subprocess, so we kill it manually.
        kill_process_group(process)
        await process.wait()
        raise

    assert process.returncode is not None

    return CommandResult(
        returncode=process.returncode,
        stdout=stdout_path.read_bytes(),
        stderr=stderr_path.read_bytes(),
        timed_out=timed_out,
    )


@dataclass(frozen=True)
class ConfigurationResult:
    configuration: Configuration
    compilation: CommandResult
    execution: CommandResult | None


def source_filename(configuration: Configuration, seed: int) -> str:
    # Some compiler bugs depend on the source filename or compilation-unit name.
    # Vary names across configurations so output comparisons can expose them,
    # without depending on scheduling or the case RNG.
    digest = hashlib.sha256(f"{seed}:{configuration.name}".encode()).hexdigest()
    return f"program_{digest[:16]}.ml"


def compile_command(
    configuration: Configuration, *, source: Path, executable: Path
) -> list[str]:
    return [
        str(configuration.compiler),
        *configuration.flags,
        "-o",
        str(executable),
        str(source),
    ]


async def compile(
    configuration: Configuration,
    *,
    source: Path,
    executable: Path,
) -> CommandResult:
    command = compile_command(configuration, source=source, executable=executable)
    return await run_command(
        command[0],
        command[1:],
        cwd=source.parent,
        env={"OCAMLLIB": str(configuration.ocamllib)},
        timeout_sec=COMPILE_TIMEOUT_SEC,
        output_prefix=source.parent / "compile",
    )


async def run(executable: Path) -> CommandResult:
    try:
        return await run_command(
            str(executable),
            [],
            cwd=executable.parent,
            timeout_sec=RUN_TIMEOUT_SEC,
            output_prefix=executable.parent / "run",
        )
    except OSError as error:
        # The executable could not be started, report it with the shell's exit
        # codes for "not found" (127) and "cannot execute" (126).
        return CommandResult(
            returncode=127 if error.errno == errno.ENOENT else 126,
            stdout=b"",
            stderr=f"{executable}: {error.strerror}\n".encode(),
            timed_out=False,
        )


async def run_configuration(
    configuration: Configuration,
    *,
    seed: int,
    program: bytes,
    work_dir: Path,
    slots: asyncio.Semaphore,
) -> ConfigurationResult:
    async with slots:
        work_dir.mkdir(parents=True)
        source = work_dir / source_filename(configuration, seed)
        source.write_bytes(program)
        executable = work_dir / "program.exe"
        compilation = await compile(configuration, source=source, executable=executable)
        if not compilation.ok:
            return ConfigurationResult(
                configuration=configuration, compilation=compilation, execution=None
            )

        execution = await run(executable)
        return ConfigurationResult(
            configuration=configuration, compilation=compilation, execution=execution
        )


async def run_configurations(
    toolchain: Toolchain,
    *,
    seed: int,
    program: bytes,
    work_dir: Path,
    slots: asyncio.Semaphore,
) -> list[ConfigurationResult]:
    return await asyncio.gather(
        *(
            run_configuration(
                configuration,
                seed=seed,
                program=program,
                work_dir=work_dir / configuration.name,
                slots=slots,
            )
            for configuration in toolchain.configurations
        )
    )


# Returns None if generation timed out.
async def generate(seed: int, *, toolchain: Toolchain, work_dir: Path) -> bytes | None:
    work_dir.mkdir(parents=True, exist_ok=True)
    result = await run_command(
        str(toolchain.oxfuzzer),
        ["-seed", str(seed)],
        timeout_sec=GENERATE_TIMEOUT_SEC,
        output_prefix=work_dir / "generate",
    )
    stderr = result.stderr.decode(errors="replace")
    if result.timed_out:
        return None
    # CR-soon xclerc: This should not interrupt the fuzzing campaign,
    # it should probably be reported as a standard failure and saved to
    # investigate the generator bug.

    # Generation failing is a fatal error.
    if result.returncode != 0:
        raise SystemExit(
            f"generation exited with code {result.returncode}. seed: {seed}.\n"
            f"{stderr}"
        )

    return result.stdout


@dataclass
class Stats:
    """Statistics of a fuzzer's run. Describes how many programs passed, were
    discarded or failed."""

    passed: int = 0
    discarded: int = 0
    failed: int = 0
    generation_timeouts: int = 0
    last_completion: float | None = None
    smoothed_interval: float | None = None
    last_report: float | None = None

    def record_completion(self) -> None:
        now = time.monotonic()
        if self.last_completion is not None:
            interval = now - self.last_completion
            if self.smoothed_interval is None:
                self.smoothed_interval = interval
            else:
                self.smoothed_interval += RATE_SMOOTHING * (
                    interval - self.smoothed_interval
                )
        self.last_completion = now

    def cases_per_hour(self) -> float | None:
        if not self.smoothed_interval:
            return None
        return 3600 / self.smoothed_interval

    def summary(self) -> str:
        rate = self.cases_per_hour()
        rate_text = "--" if rate is None else f"{rate:,.0f}"
        return (
            f"{self.passed} passed, {self.discarded} discarded, "
            f"{self.failed} failed, {rate_text} cases/h"
        )

    def print_line(self) -> None:
        timestamp = time.strftime("%Y-%m-%d %H:%M:%S")
        print(f"{timestamp} {self.summary()}", file=sys.stderr, flush=True)

    # On a terminal the status is a single line updated in place. Otherwise
    # a timestamped line is printed at most every PROGRESS_INTERVAL_SEC seconds.
    def report(self) -> None:
        self.record_completion()
        if sys.stderr.isatty():
            print(f"\r{self.summary()}", end="", file=sys.stderr, flush=True)
            return
        now = time.monotonic()
        if (
            self.last_report is not None
            and now - self.last_report < PROGRESS_INTERVAL_SEC
        ):
            return
        self.last_report = now
        self.print_line()

    def final_report(self) -> None:
        if sys.stderr.isatty():
            print(file=sys.stderr)
        else:
            self.print_line()
        print(
            f"oxfuzzer: {self.generation_timeouts} generations timed out",
            file=sys.stderr,
        )


def command_output(command: Sequence[str], *, cwd: Path | None = None) -> str | None:
    try:
        completed = subprocess.run(
            command, cwd=cwd, capture_output=True, text=True, timeout=30
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if completed.returncode != 0:
        return None
    return completed.stdout.strip()


def source_revision(directory: Path) -> str:
    # We try to get both the git and hg revision as both may be potentially used.
    revision = command_output(["git", "rev-parse", "HEAD"], cwd=directory)
    if revision is not None:
        dirty = command_output(
            ["git", "status", "--porcelain", "--untracked-files=no"],
            cwd=directory,
        )
        return f"git {revision}{' (dirty)' if dirty else ''}"
    revision = command_output(["hg", "id", "-i"], cwd=directory)
    if revision is not None:
        return f"hg {revision}"  # hg appends '+' itself when dirty.
    return "unknown"


def run_metadata(base_seed: str, toolchain: Toolchain, revision: str) -> str:
    lines = [
        f"command: {shlex.join(sys.argv)}",
        f"base seed: {base_seed}",
        f"host: {platform.node()}",
        f"platform: {platform.platform()}",
        f"python: {sys.version.split()[0]}",
        f"source revision: {revision}",
        f"toolchain: {toolchain.root}{' (installed)' if toolchain.installed else ''}",
        f"ocamlopt version: {command_output([str(toolchain.ocamlopt), '-version']) or 'unknown'}",
        f"ocamlc version: {command_output([str(toolchain.ocamlc), '-version']) or 'unknown'}",
        f"OCAMLLIB: {toolchain.ocamllib}",
        f"OCAMLPARAM: {os.environ.get('OCAMLPARAM', '(unset)')}",
        f"OCAMLRUNPARAM: {os.environ.get('OCAMLRUNPARAM', '(unset)')}",
        f"compile timeout: {COMPILE_TIMEOUT_SEC}s",
        f"run timeout: {RUN_TIMEOUT_SEC}s",
    ]
    for binary in (toolchain.oxfuzzer, *(c.compiler for c in toolchain.configurations)):
        modified = time.strftime(
            "%Y-%m-%d %H:%M:%S", time.localtime(binary.stat().st_mtime)
        )
        lines.append(f"binary: {binary} (modified {modified})")
    return "\n".join(lines) + "\n"


def failure_metadata(seed: int, run_info: str) -> str:
    return (
        f"seed: {seed}\n" f"time: {time.strftime('%Y-%m-%d %H:%M:%S %z')}\n" + run_info
    )


def status_text(result: CommandResult) -> str:
    if result.timed_out:
        return "timeout"
    if result.returncode < 0:
        return f"signal {-result.returncode}"
    return str(result.returncode)


def write_command_result(directory: Path, prefix: str, result: CommandResult) -> None:
    (directory / f"{prefix}.status").write_text(status_text(result) + "\n")
    (directory / f"{prefix}.stdout").write_bytes(result.stdout)
    (directory / f"{prefix}.stderr").write_bytes(result.stderr)


def reproduction_script(
    configuration: Configuration,
    seed: int,
    *,
    toolchain: Toolchain,
    directory: Path,
) -> str:
    if not toolchain.installed:
        toolchain = Toolchain(
            Path(os.path.relpath(toolchain.root.resolve(), directory.resolve()))
        )
    configuration = next(
        candidate
        for candidate in toolchain.configurations
        if candidate.name == configuration.name
    )
    source = Path(source_filename(configuration, seed))
    command = compile_command(
        configuration, source=source, executable=Path("program.exe")
    )
    # CR-soon xclerc: We should also capture OCAMLPARAM and OCAMLRUNPARAM,
    # which are inherited by compilation and execution by default, but may differ
    # in the shell, which executes run.bash.
    # No #! line, and the file is not named *.sh: some download filters reject
    # an archive of failures that contains either.
    return "\n".join(
        [
            f"# oxfuzzer: configuration {configuration.name}, seed {seed}.",
            "# Run with: bash run.bash",
            "set -eu",
            'cd "$(dirname "$0")"',
            f"export OCAMLLIB={shlex.quote(str(configuration.ocamllib))}",
            # Keep program.ml editable for minimization, but preserve the basename.
            shlex.join(["cp", "../program.ml", str(source)]),
            shlex.join(command),
            "./program.exe",
            "",
        ]
    )


# Save everything needed to reproduce and diagnose a failing case under
# <output_dir>/<seed>/:
#   program.ml   the generated program
#   reason.txt   why the case failed
#   meta.txt     seed, time and the run-level metadata (see run_metadata)
#   <config>/    one directory per configuration containing run.bash (a
#                standalone reproducer), compile.{status,stdout,stderr} and,
#                if the program was run, run.{status,stdout,stderr}
# The directory is written under a temporary name and renamed into place, so
# that a run killed while saving does not leave a partial failure directory.
def save_failure(
    output_dir: Path,
    run_info: str,
    seed: int,
    program: bytes,
    results: Sequence[ConfigurationResult],
    reason: str,
    *,
    toolchain: Toolchain,
) -> None:
    failure_dir = output_dir / str(seed)
    # Dot-prefixed, so that a leftover is not taken for a failure.
    staging_dir = Path(tempfile.mkdtemp(prefix=f".{seed}.", dir=output_dir))
    staging_dir.chmod(0o755)
    (staging_dir / "program.ml").write_bytes(program)
    (staging_dir / "reason.txt").write_text(reason + "\n")
    (staging_dir / "meta.txt").write_text(failure_metadata(seed, run_info))
    for result in results:
        directory = staging_dir / result.configuration.name
        directory.mkdir()
        script = directory / "run.bash"
        script.write_text(
            reproduction_script(
                result.configuration,
                seed,
                toolchain=toolchain,
                directory=failure_dir / result.configuration.name,
            )
        )
        script.chmod(0o755)
        write_command_result(directory, "compile", result.compilation)
        if result.execution is not None:
            write_command_result(directory, "run", result.execution)
    # Replace a failure saved by an earlier run into the same output directory.
    shutil.rmtree(failure_dir, ignore_errors=True)
    staging_dir.rename(failure_dir)
    print(f"\nseed {seed}: {reason}", file=sys.stderr)


# A case passes when every configuration compiles and runs successfully and
# the outputs (stdout, stderr) are identical. A case is discarded when any
# execution times out. A case fails when any compilation times out or fails,
# any execution exits with a non-zero status, or the outputs differ.
def check_case(
    seed: int,
    program: bytes,
    results: Sequence[ConfigurationResult],
    stats: Stats,
    output_dir: Path,
    run_info: str,
    *,
    toolchain: Toolchain,
) -> None:
    def fail(reason: str) -> None:
        save_failure(
            output_dir,
            run_info,
            seed,
            program,
            results,
            reason,
            toolchain=toolchain,
        )
        stats.failed += 1
        stats.report()

    failed = [r for r in results if not r.compilation.ok]
    if failed:
        names = ", ".join(
            f"{r.configuration.name} ({status_text(r.compilation)})" for r in failed
        )
        fail(f"compilation failed or timed out: {names}")
        return

    # CR-soon xclerc: This is a bug, execution failures should take
    # precedence over timeouts and if any execution fails the test is considered
    # a failure.

    # Every configuration compiled the program, so every one ran it.
    executions = [
        (r.configuration, r.execution) for r in results if r.execution is not None
    ]
    # If any of the executions time out, we discard the case.
    if any(execution.timed_out for _, execution in executions):
        stats.discarded += 1
        stats.report()
        return
    # Generated programs terminate normally by construction, so a non-zero exit
    # is a bug in the generator, the compiler or the runtime, even when all
    # configurations agree on it.
    error = [(c, execution) for c, execution in executions if execution.returncode != 0]
    if error:
        names = ", ".join(
            f"{c.name} ({status_text(execution)})" for c, execution in error
        )
        fail(f"error exit: {names}")
        return
    (reference_configuration, reference), *others = executions
    for other_configuration, other in others:
        reference_outcome = (reference.stdout, reference.stderr)
        other_outcome = (other.stdout, other.stderr)

        if reference_outcome != other_outcome:
            fail(
                f"{reference_configuration.name} and "
                f"{other_configuration.name} disagree"
            )
            return
    stats.passed += 1
    stats.report()


async def run_case(
    toolchain: Toolchain,
    run_dir: Path,
    seed: int,
    stats: Stats,
    output_dir: Path,
    run_info: str,
    slots: asyncio.Semaphore,
) -> None:
    case_dir = run_dir / f"case-{seed}"
    try:
        program = await generate(seed, toolchain=toolchain, work_dir=case_dir)
        if program is None:
            stats.generation_timeouts += 1
        if program is None or len(program) > MAX_PROGRAM_BYTES:
            stats.discarded += 1
            stats.report()
            return
        results = await run_configurations(
            toolchain, seed=seed, program=program, work_dir=case_dir, slots=slots
        )
        check_case(
            seed, program, results, stats, output_dir, run_info, toolchain=toolchain
        )
    finally:
        shutil.rmtree(case_dir, ignore_errors=True)


SELF_CHECK_SEED = 0

