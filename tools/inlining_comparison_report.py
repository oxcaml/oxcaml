def parse_narrative(path):
    sections = {}
    if not path or not os.path.exists(path):
        return sections
    cur = None
    with open(path) as fh:
        for line in fh:
            m = re.match(r'^##\s+(\S+)', line)
            if m:
                cur = m.group(1).strip('`')
                sections[cur] = []
            elif cur is not None:
                sections[cur].append(line.rstrip('\n'))
    return {k: '\n'.join(v).strip() for k, v in sections.items()}


def md_inline(text):
    t = html.escape(text)
    t = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', t)
    t = re.sub(r'`(.+?)`', r'<font face="Courier" size="8.5">\1</font>', t)
    return t


def narrative_flowables(text, styles):
    from reportlab.platypus import Paragraph, Spacer
    out = []
    if not text:
        out.append(Paragraph('<i>Commentary to be written from NARRATIVE_PROMPT.md.</i>', styles['note']))
        return out
    para = []
    def flush():
        if para:
            out.append(Paragraph(md_inline(' '.join(para)), styles['body']))
            para.clear()
    for line in text.split('\n'):
        s = line.strip()
        if not s:
            flush()
        elif s.startswith('- ') or s.startswith('* '):
            flush()
            out.append(Paragraph(md_inline(s[2:]), styles['bullet'], bulletText='•'))
        else:
            para.append(s)
    flush()
    return out


