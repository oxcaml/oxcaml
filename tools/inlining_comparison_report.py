    story.append(Paragraph(html.escape(cfg['title']), styles['title']))
    m0 = metas[names[0]]
    story.append(Paragraph(html.escape(
        f"Generated {out['generated'][:10]} on {m0['host']} ({m0['machine']}); tree {m0['tree']} at "
        f"{', '.join(sorted({metas[n]['commit'] for n in names}))}. Sizes quoted in model units are the "
        f"{out['arch']} estimates of each configuration's own code size model and are not comparable "
        f"between configurations; byte counts and decision counts are."), styles['sub']))
    story.append(Paragraph('Summary', styles['h2']))
    story += narrative_flowables(nar.get('summary'), styles)

    # table 1
    two = len(names) == 2
    rows = [[Paragraph('metric', styles['th'])] + [Paragraph(html.escape(n), styles['th']) for n in names]
            + ([Paragraph('change', styles['th'])] if two else [])]
    def trow(label, key, fmt=fmt_int, src=st, comparable=True):
        cells = [fmt(src[n][key]) if src[n].get(key) is not None else 'n/a' for n in names]
        if two:
            a, b = src[names[0]].get(key), src[names[1]].get(key)
            cells.append(f'{100.0 * (b - a) / a:+.1f}%' if comparable and a and b is not None else '')
        rows.append([Paragraph(html.escape(label), styles['td'])] + cells)
    trow('build wall time (s)', 'wall_seconds', lambda x: f'{x:.0f}', metas)
    trow('build CPU time (s)', 'cpu_seconds', lambda x: f'{x:.0f}', metas)
    trow('OCaml object text size (bytes)', 'object_text_total')
    trow('speculative decisions (all outcomes)', 'decisions')
    trow('judged after a full speculation', 'decided')
    trow('aborted by the budget', 'aborted')
    trow('refused before speculating', 'budget_refused')
    rows.append([Paragraph('functor applications: speculated / inlined', styles['td'])] +
                [f"{fmt_int(st[n]['functor_decisions'])} / {fmt_int(st[n]['functor_inlined'])}" for n in names]
                + ([''] if two else []))
    trow('inlined', 'inlined')
    trow('rejected', 'rejected')
    trow('share inlined', 'inlined_share', lambda x: f'{100 * x:.1f}%', comparable=False)
    trow('distinct callees inlined', 'distinct_callees_inlined')
    trow('inlined body size, total (model units)', 'inlined_body_total', comparable=False)
    trow('inlined body size, median (model units)', 'inlined_body_median', lambda x: f'{x:.0f}', comparable=False)
    trow('speculation work (model units)', 'speculation_work', comparable=False)
    trow('direct call instructions', 'direct_calls')
    trow('indirect call instructions', 'indirect_calls')
    trow('generic applications (caml_apply, caml_send)', 'generic_applies')
    trow('unknown-callee call sites (reports)', 'unknown_callee_sites')
    story.append(Spacer(1, 4))
    ncols = len(names) + (1 if two else 0)
    story.append(KeepTogether([table(rows, [W * 0.46] + [W * 0.54 / ncols] * ncols),
                               Paragraph('<b>Table 1.</b> Headline measurements per configuration.', styles['caption'])]))

    story.append(Paragraph('Where inlining happens', styles['h2']))
    story += figure('probability.png', 1, 'Share of speculative decisions that inline, by callee size before inlining, for each configuration. Callees below a configuration\'s small function size are inlined without speculation and do not appear.')
    story += narrative_flowables(nar.get('fig-probability'), styles)
    story += figure('inlined.png', 2, 'Number of inlined decisions by callee size.')
    story += narrative_flowables(nar.get('fig-inlined'), styles)
    story.append(Paragraph('Code growth', styles['h2']))
    story += figure('body.png', 3, 'Total size of the bodies inlined after speculation, by callee size, in each configuration\'s own model units.')
    story += narrative_flowables(nar.get('fig-body'), styles)
    story += figure('shrink.png', 4, 'Ratio of the simplified size to the size before inlining, one point per completed speculation, with the median per size bin; aborted speculations have no simplified size and are absent.')
    story += narrative_flowables(nar.get('fig-shrink'), styles)
    if len(names) >= 2 and os.path.exists(os.path.join(data_dir, 'figures', 'objects.png')):
        story.append(Paragraph('Generated code size', styles['h2']))
        story += figure('objects.png', 5, f'Directories with the largest change in OCaml object text size, {names[-1]} minus {names[0]} (red: larger, blue: smaller).')
        story += narrative_flowables(nar.get('fig-objects'), styles)
        rows = [[Paragraph('directory', styles['th']), Paragraph('change (bytes)', styles['th'])]]
        for d, v in list(out['object_dir_deltas'].items())[:14]:
            rows.append([Paragraph(html.escape(d), styles['td']), f'{v:+,}'])
        story.append(KeepTogether([table(rows, [W * 0.7, W * 0.3]),
                                   Paragraph('<b>Table 3.</b> Object text size change by directory, largest first.', styles['caption'])]))

    story.append(Paragraph('Callees contributing most inlined code', styles['h2']))
    for n in names:
        rows = [[Paragraph(h, styles['th']) for h in ('callee', 'calls', 'size before', 'inlined total', 'median body')]]
        for t in st[n]['top_callees']:
            rows.append([Paragraph(html.escape(t['callee']), styles['td']), str(t['calls']), fmt_int(t['orig']),
                         fmt_int(t['body']), fmt_int(t['median_body'])])
        story.append(KeepTogether([table(rows, [W * 0.52, W * 0.1, W * 0.12, W * 0.14, W * 0.12]),
                                   Paragraph(f'<b>Table 2 ({html.escape(n)}).</b> Callees by total inlined body size ({html.escape(metas[n]["size_units"])}).', styles['caption'])]))
    story += narrative_flowables(nar.get('table-callees'), styles)

    story.append(Paragraph('Functor applications', styles['h2']))
    for n in names:
        rows = [[Paragraph(h, styles['th']) for h in ('functor', 'applications', 'inlined', 'rejected', 'aborted or refused', 'size before')]]
        for t in st[n]['functors']:
            rows.append([Paragraph(html.escape(t['functor']), styles['td']), str(t['applications']), str(t['inlined']),
                         str(t['rejected']), str(t['aborted']), fmt_int(t['size'])])
        if len(rows) > 1:
            story.append(KeepTogether([table(rows, [W * 0.46, W * 0.12, W * 0.09, W * 0.09, W * 0.13, W * 0.11]),
                                       Paragraph(f'<b>Table 4 ({html.escape(n)}).</b> Functor applications by functor, most applied first ({html.escape(metas[n]["size_units"])}).', styles['caption'])]))
    story += narrative_flowables(nar.get('functors'), styles)

    if out.get('call_deltas_top'):
        story.append(Paragraph('Direct and indirect calls', styles['h2']))
        a, b = names[0], names[-1]
        rows = [[Paragraph(h, styles['th']) for h in ('object', a, b, 'change')]]
        for p, va, vb, d in out['call_deltas_top'][:12]:
            rows.append([Paragraph(html.escape(p.split('/')[-1]), styles['td']), str(va), str(vb), f'{d:+}'])
        story.append(KeepTogether([table(rows, [W * 0.55, W * 0.15, W * 0.15, W * 0.15]),
                                   Paragraph('<b>Table 5.</b> Objects with the largest increase in indirect calls plus generic applications.', styles['caption'])]))
        if out.get('unknown_deltas_top'):
            rows = [[Paragraph(h, styles['th']) for h in ('unit', a, b, 'change')]]
            for u, va, vb, d in out['unknown_deltas_top'][:12]:
                rows.append([Paragraph(html.escape(u), styles['td']), str(va), str(vb), f'{d:+}'])
            story.append(KeepTogether([table(rows, [W * 0.55, W * 0.15, W * 0.15, W * 0.15]),
                                       Paragraph('<b>Table 6.</b> Units with the largest increase in call sites whose callee was unknown to Flambda 2.', styles['caption'])]))
        story += narrative_flowables(nar.get('calls'), styles)

    if cfg.get('watch_callees'):
        story.append(Paragraph('Watched callees', styles['h2']))
        for prefix in cfg['watch_callees']:
            rows = [[Paragraph(h, styles['th']) for h in ('outcome and reason',) + tuple(names)]]
            keys = [k for k in REASONS if any(st[n]['watched'].get(prefix, {}).get(k) for n in names)]
            for k in keys:
                rows.append([Paragraph(html.escape(k), styles['td'])] + [str(st[n]['watched'].get(prefix, {}).get(k, 0)) for n in names])
            rows.append([Paragraph('<b>call sites in total</b>', styles['td'])] + [str(st[n]['watched'].get(prefix, {}).get('sites', 0)) for n in names])
            rows.append([Paragraph('unknown-callee sites inside its unit', styles['td'])] + [str(st[n]['watched'].get(prefix, {}).get('unknown_sites_in_unit', 0)) for n in names])
            if any(st[n]['watched'].get(prefix, {}).get('unit_calls') for n in names):
                rows.append([Paragraph('its object: direct / indirect / generic calls', styles['td'])] +
                            [(lambda uc: f"{uc['direct']} / {uc['indirect']} / {uc['generic']}" if uc else 'n/a')(st[n]['watched'].get(prefix, {}).get('unit_calls')) for n in names])
            story.append(KeepTogether([table(rows, [W * 0.5] + [W * 0.5 / len(names)] * len(names)),
                                       Paragraph(f'<b>Table 7.</b> Call sites to {html.escape(prefix)} by outcome.', styles['caption'])]))
        story += narrative_flowables(nar.get('watched'), styles)

    story.append(Paragraph('Conclusions', styles['h2']))
    story += narrative_flowables(nar.get('conclusions'), styles)

    story.append(PageBreak())
    story.append(Paragraph('Method and configurations', styles['h2']))
    for n in names:
        m = metas[n]
        story.append(Paragraph(md_inline(
            f"**{n}**: {m['label']}. " + (f"Clean: `{m['clean']}`. " if m['clean'] else '') +
            f"Build: `{m['command']}` with {', '.join(f'`{k}={v}`' for k, v in m['env'].items()) or 'no extra environment'}. "
            f"Reports: {m['report_summary']['files']} files, {m['report_summary']['decisions']} call-site decisions "
            f"(outcomes {json.dumps(m['report_summary']['outcomes'])}). Objects: {st[n]['object_count']} files."), styles['note']))
    story.append(Paragraph(md_inline(
        'Decisions are read from the `.inlining.org` reports with `tools/inlining_decisions.py`; a callee\'s size '
        'before inlining is the one its call site saw. Object sizes are those of `.o` files that have a `.cmx` '
        f"beside them (measure: {', '.join(sorted({metas[n].get('object_size_measure', 'text section') for n in names}))}). "
        'Decisions from every optimisation level are pooled; in figures 1 to 3 an aborted or refused speculation '
        f'counts as a decision not to inline. Bins with fewer than {MIN_BIN} decisions are omitted from the figures. '
        'Functor applications are counted in the totals but excluded from the inlined counts and the size '
        'figures.'), styles['note']))
    doc = SimpleDocTemplate(out_pdf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm,
                            topMargin=14 * mm, bottomMargin=14 * mm, title=cfg['title'])
    doc.build(story)
    print(f'wrote {out_pdf}')


