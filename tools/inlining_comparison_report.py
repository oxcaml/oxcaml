"""Compare speculative inlining configurations and produce a PDF report.

The work is split so that the commentary is written by a person or an LLM
from the measured numbers, not generated by this script:

  run       in a source tree, for each configuration: run its clean and
            build commands (timed), harvest the .inlining.org reports and
            the sizes of the OCaml objects; then do what `analyse` does
  analyse   from harvested data: compute the statistics, draw the figures,
            write NARRATIVE_PROMPT.md (a self-contained request for the
            commentary, carrying every number) and a draft PDF whose
            commentary is placeholder text
  render    assemble the final PDF from the analysis and narrative.md

Typical use on the compiler tree:

  tools/inlining_comparison_report.py run --preset oxcaml --data report-data
  # write report-data/narrative.md from report-data/NARRATIVE_PROMPT.md
  tools/inlining_comparison_report.py render --data report-data report.pdf

For another tree, start from `example-config` and pass --config FILE.
Needs Python 3 with numpy, matplotlib and reportlab; scipy is optional
(fitted curves). The `size` tool from binutils (or the macOS one) is used
for object sizes.
"""
