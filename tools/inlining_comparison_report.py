def f(x, default=None):
    try:
        return float(x)
    except (TypeError, ValueError):
        return default


def bin_index(size):
    for i, e in enumerate(BIN_EDGES):
        if i + 1 == len(BIN_EDGES) or size < BIN_EDGES[i + 1]:
            return i
    return len(BIN_EDGES) - 1


def bin_label(i):
    if i + 1 < len(BIN_EDGES):
        return f'{BIN_EDGES[i]}-{BIN_EDGES[i + 1] - 1}'
    return f'{BIN_EDGES[i]}+'


def per_config_stats(rows, arch):
    o_col, s_col = 'orig_' + arch, 'simp_' + arch
    st = {}
    outcomes = Counter(r['outcome'] for r in rows)
    st['decisions'] = len(rows)
    st['decided'] = outcomes.get('decided', 0)
    st['aborted'] = outcomes.get('aborted', 0)
    st['budget_refused'] = outcomes.get('budget_exhausted', 0)
    decided = [r for r in rows if r['outcome'] == 'decided' and r['functor'] != 'True']
    inl = [r for r in decided if r['inlined'] == 'True']
    functors = [r for r in rows if r['functor'] == 'True']
    st['functor_decisions'] = len(functors)
    st['functor_inlined'] = sum(1 for r in functors if r['outcome'] == 'decided' and r['inlined'] == 'True')
    st['functor_not_completed'] = sum(1 for r in functors if r['outcome'] != 'decided')
    st['inlined'] = len(inl)
    st['rejected'] = len(decided) - len(inl)
    st['inlined_share'] = len(inl) / len(decided) if decided else 0.0
    st['distinct_callees_inlined'] = len({r['callee'] for r in inl})
    bodies = [f(r[s_col], 0.0) for r in inl]
    st['inlined_body_total'] = sum(bodies)
    st['inlined_body_median'] = median(bodies) if bodies else 0.0
    work = [f(r[o_col]) for r in rows if r['outcome'] != 'budget_exhausted']
    st['speculation_work'] = sum(w for w in work if w is not None)
    # Every non-functor speculation with a known callee size, whatever its
    # outcome: an aborted or refused speculation is a decision not to inline.
    sized = [r for r in rows if r['functor'] != 'True' and f(r[o_col]) is not None]
    st['sized_decisions'] = len(sized)
    bins = defaultdict(lambda: {'n': 0, 'inlined': 0, 'aborted': 0, 'body': 0.0})
    for r in sized:
        b = bins[bin_index(int(f(r[o_col])))]
        b['n'] += 1
        if r['outcome'] != 'decided':
            b['aborted'] += 1
        elif r['inlined'] == 'True':
            b['inlined'] += 1
            b['body'] += f(r[s_col], 0.0)
    st['bins'] = {bin_label(i): bins[i] for i in sorted(bins)}
    thr_rows = decided  # completed speculations, which have a simplified size
    callees = defaultdict(lambda: {'calls': 0, 'body': 0.0, 'orig': 0.0, 'bodies': []})
    for r in inl:
        k = callees[r['callee']]
        k['calls'] += 1
        k['body'] += f(r[s_col], 0.0)
        k['orig'] = f(r[o_col], 0.0)
        k['bodies'].append(f(r[s_col], 0.0))
    top = sorted(callees.items(), key=lambda kv: -kv[1]['body'])[:12]
    st['top_callees'] = [{'callee': k, 'calls': v['calls'], 'body': v['body'],
                          'orig': v['orig'], 'median_body': median(v['bodies'])}
                         for k, v in top]
    st['shrink'] = [(f(r[o_col]), f(r[s_col]), r['inlined'] == 'True')
                    for r in thr_rows if f(r[o_col], 0) > 0]
    ratios = [s / o for o, s, _ in st['shrink']]
    st['shrink_median_ratio'] = median(ratios) if ratios else None
    return st


