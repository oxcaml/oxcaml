def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    p = sub.add_parser('run', help='build each configuration, harvest, analyse')
    p.add_argument('--preset', choices=sorted(PRESETS))
    p.add_argument('--config', help='JSON configuration file (see example-config)')
    p.add_argument('--tree', help='override the tree the commands run in')
    p.add_argument('--data', default='inlining-report-data', help='directory for harvested data and outputs')
    p.add_argument('--skip-build', action='store_true', help='harvest what is already built (keeps recorded build times)')
    p.add_argument('--only', action='append', help='only this configuration (repeatable), e.g. to re-harvest one')
    p = sub.add_parser('analyse', help='recompute statistics, figures, prompt and draft from harvested data')
    p.add_argument('--data', default='inlining-report-data')
    p = sub.add_parser('render', help='assemble the final PDF from the analysis and the narrative')
    p.add_argument('--data', default='inlining-report-data')
    p.add_argument('--narrative', help='narrative Markdown (default: <data>/narrative.md)')
    p.add_argument('out_pdf')
    sub.add_parser('example-config', help='print a configuration file to adapt for another tree')
    args = ap.parse_args()
    if args.cmd == 'run':
        cmd_run(args)
    elif args.cmd == 'analyse':
        analyse(os.path.abspath(args.data))
    elif args.cmd == 'render':
        data = os.path.abspath(args.data)
        nar = args.narrative or os.path.join(data, 'narrative.md')
        render(data, args.out_pdf, nar if os.path.exists(nar) else None)
    elif args.cmd == 'example-config':
        ex = json.loads(json.dumps(PRESETS['oxcaml']))
        ex['tree'] = '/path/to/tree'
        ex['title'] = 'Speculative inlining on <project>'
        ex['report_dirs'] = ex['object_dirs'] = ['_build/default']
        for c in ex['configs']:
            c['clean'] = 'dune clean'
            c['command'] = 'dune build @install'
            c['env'] = {'OCAMLPARAM': c['env']['BUILD_OCAMLPARAM']}
        print(json.dumps(ex, indent=2))


if __name__ == '__main__':
    main()
