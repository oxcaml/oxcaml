        a, b = configs[0]['name'], configs[-1]['name']
        by_dir_a, by_dir_b = Counter(), Counter()
        for p, v in objects[a].items():
            by_dir_a[dir_key(p)] += v
        for p, v in objects[b].items():
            by_dir_b[dir_key(p)] += v
