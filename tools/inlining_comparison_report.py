def run_command(cmd, cwd, env):
    print(f'+ {cmd}', flush=True)
    before = resource.getrusage(resource.RUSAGE_CHILDREN)
    t0 = time.time()
    r = subprocess.run(cmd, shell=True, cwd=cwd, env=env)
    wall = time.time() - t0
    after = resource.getrusage(resource.RUSAGE_CHILDREN)
    cpu = (after.ru_utime - before.ru_utime) + (after.ru_stime - before.ru_stime)
    if r.returncode != 0:
        sys.exit(f'command failed with status {r.returncode}: {cmd}')
    return wall, cpu


def ocaml_objects(tree, object_dirs):
    """Paths of .o files that have a .cmx beside them (OCaml-generated code)."""
    out = []
    for d in object_dirs:
        for root, _, files in os.walk(os.path.join(tree, d)):
            names = set(files)
            for fn in files:
                if fn.endswith('.o') and fn[:-2] + '.cmx' in names:
                    out.append(os.path.join(root, fn))
    return sorted(out)


def parse_size_output(stdout):
    """Text sizes from the output of `size` (GNU binutils Berkeley format or
    the macOS tool): one row per object, first column the text size, header
    lines mentioning `text` or `__TEXT` skipped."""
    out = []
    for line in stdout.splitlines():
        if not line.strip() or re.search(r'\btext\b|__TEXT', line):
            continue
        tok = line.split()[0]
        if tok.isdigit():
            out.append(int(tok))
    return out


def size_tool_available():
    try:
        subprocess.run(['size', '--version'], capture_output=True)
        return True
    except OSError:
        return False


def text_sizes(paths):
    """Text section size in bytes of each object via the `size` tool, or the
    file size when the tool is not installed. Returns (sizes, measure)."""
    if not size_tool_available():
        print("  warning: `size` (binutils) not found; using file sizes instead", flush=True)
        return {p: os.path.getsize(p) for p in paths}, 'file size'
    sizes = {}
    chunk = 200
    for i in range(0, len(paths), chunk):
        batch = paths[i:i + chunk]
        r = subprocess.run(['size'] + batch, capture_output=True, text=True)
        rows = parse_size_output(r.stdout)
        if len(rows) != len(batch):
            for p in batch:  # fall back to one call per file
                r1 = subprocess.run(['size', p], capture_output=True, text=True)
                rows1 = parse_size_output(r1.stdout)
                sizes[p] = rows1[0] if rows1 else 0
            continue
        for p, v in zip(batch, rows):
            sizes[p] = v
    return sizes, 'text section'


def objdump_available():
    try:
        subprocess.run(['objdump', '--version'], capture_output=True)
        return True
    except OSError:
        return False


def count_calls(path):
    """(direct calls, indirect calls, generic applications) in one object.

    Direct calls are `bl` (arm64) or `call` to a symbol (x86-64); indirect
    calls are `blr` or `call *reg`; generic applications are relocations to
    caml_applyN or caml_sendN, the calls made when the callee or its arity is
    unknown. Works with GNU and LLVM objdump."""
    direct = indirect = generic = 0
    r = subprocess.run(['objdump', '-d', '-r', path], capture_output=True, text=True,
                       errors='replace')
    for line in r.stdout.splitlines():
        if 'caml_apply' in line or 'caml_send' in line:
            if 'RELOC' in line or 'R_' in line:
                generic += 1
                continue
        # GNU objdump: "addr:<tab>bytes<tab>mnemonic<tab>operands" (x86 puts the
        # operands in the mnemonic's field); LLVM objdump: "addr: bytes<tab>
        # mnemonic<tab>operands". Take the first field that starts like a
        # mnemonic.
        parts = line.split('\t')
        m = ops = None
        for i in range(1, len(parts)):
            toks = parts[i].split()
            if not toks or all(re.fullmatch(r'[0-9a-f]{2}', t) for t in toks) \
                    or (len(toks) == 1 and re.fullmatch(r'[0-9a-f]{8}', toks[0])):
                continue  # the instruction's bytes
            mm = re.match(r'^([a-z][a-z0-9.]*)(?:\s+(.*))?$', parts[i].strip())
            if mm:
                m = mm.group(1)
                ops = mm.group(2) or (parts[i + 1].strip() if i + 1 < len(parts) else '')
                break
        if m is None:
            continue
        if m == 'bl' or (m in ('call', 'callq') and not ops.startswith('*')):
            direct += 1
        elif m == 'blr' or (m in ('call', 'callq') and ops.startswith('*')):
            indirect += 1
    return direct, indirect, generic


def harvest(cfg, c, data_dir, build_timing):
    tree = cfg['tree']
    cdir = os.path.join(data_dir, c['name'])
    os.makedirs(cdir, exist_ok=True)
    spec = importlib.util.spec_from_file_location(
        'inlining_decisions', os.path.join(HERE, 'inlining_decisions.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    roots = [os.path.join(tree, d) for d in cfg['report_dirs']]
    summary = mod.collect(roots, os.path.join(cdir, 'decisions.csv'))
    print(f"  reports: {summary}")
    objs = ocaml_objects(tree, cfg['object_dirs'])
    sizes, measure = text_sizes(objs)
    with open(os.path.join(cdir, 'objects.csv'), 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['path', 'text_bytes'])
        for p in objs:
            w.writerow([os.path.relpath(p, tree), sizes.get(p, 0)])
    print(f"  objects: {len(objs)} files, {sum(sizes.values()):,} text bytes")
    if objdump_available():
        with open(os.path.join(cdir, 'calls.csv'), 'w', newline='') as f:
            w = csv.writer(f)
            w.writerow(['path', 'direct_calls', 'indirect_calls', 'generic_applies'])
            tot = [0, 0, 0]
            for p in objs:
                d, i, g = count_calls(p)
                tot[0] += d; tot[1] += i; tot[2] += g
                w.writerow([os.path.relpath(p, tree), d, i, g])
        print(f"  calls: {tot[0]:,} direct, {tot[1]:,} indirect, {tot[2]:,} generic applications")
    else:
        print("  warning: objdump not found; call instructions not counted", flush=True)
    commit = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], cwd=tree,
                            capture_output=True, text=True).stdout.strip()
    meta = {'name': c['name'], 'label': c['label'], 'clean': c['clean'],
            'command': c['command'], 'env': c['env'], 'size_units': c['size_units'],
            'wall_seconds': build_timing[0], 'cpu_seconds': build_timing[1],
            'timestamp': datetime.datetime.now().isoformat(timespec='seconds'),
            'tree': tree, 'commit': commit, 'host': platform.node(),
            'machine': platform.machine(), 'object_size_measure': measure,
            'report_summary': summary}
    with open(os.path.join(cdir, 'meta.json'), 'w') as f:
        json.dump(meta, f, indent=2)


def cmd_run(args):
    cfg = load_config(args)
    data_dir = os.path.abspath(args.data)
    os.makedirs(data_dir, exist_ok=True)
    with open(os.path.join(data_dir, 'config.json'), 'w') as f:
        json.dump(cfg, f, indent=2)
    for c in cfg['configs']:
        if args.only and c['name'] not in args.only:
            continue
        print(f"=== configuration {c['name']}: {c['label']}", flush=True)
        env = dict(os.environ)
        env.update(c['env'])
        timing = (None, None)
        old_meta = os.path.join(data_dir, c['name'], 'meta.json')
        if args.skip_build and os.path.exists(old_meta):
            with open(old_meta) as fh:
                m = json.load(fh)
            timing = (m.get('wall_seconds'), m.get('cpu_seconds'))
        if not args.skip_build:
            if c['clean']:
                run_command(c['clean'], cfg['tree'], env)
            timing = run_command(c['command'], cfg['tree'], env)
            print(f'  build: {timing[0]:.0f} s wall, {timing[1]:.0f} s cpu')
        harvest(cfg, c, data_dir, timing)
    analyse(data_dir)


