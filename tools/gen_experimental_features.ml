(* Generate the compiler's experimental-feature registry from SCRUTINY files.
   This executable must not depend on compiler libraries: the registry is
   needed to build those libraries. *)

type review_level = Ai_reviewed | Human_reviewed

type registration =
  { path : string;
    flag : string;
    flag_line : int;
    level : review_level
  }

let fatal path line fmt =
  Printf.ksprintf
    (fun message ->
      Printf.eprintf "%s:%d: %s\n%!" path line message;
      exit 2)
    fmt

let words line =
  let length =
    match String.index_opt line '#' with
    | Some index -> index
    | None -> String.length line
  in
  let rec skip index acc =
    if index = length
    then List.rev acc
    else if Char.Ascii.is_white line.[index]
    then skip (index + 1) acc
    else word index (index + 1) acc
  and word start index acc =
    if index = length || Char.Ascii.is_white line.[index]
    then skip index (String.sub line start (index - start) :: acc)
    else word start (index + 1) acc
  in
  skip 0 []

let is_lowercase_or_digit c =
  Char.Ascii.is_lower c || Char.Ascii.is_digit c

let is_token token =
  String.length token > 0
  && is_lowercase_or_digit token.[0]
  && String.for_all
       (fun c -> is_lowercase_or_digit c || c = '.' || c = '-')
       token

let read_registration path =
  let channel = open_in path in
  Fun.protect
    ~finally:(fun () -> close_in channel)
    (fun () ->
      let rec read ~line ~flag ~level =
        match input_line channel with
        | exception End_of_file ->
          let flag, flag_line =
            match flag with
            | Some flag -> flag
            | None -> fatal path 1 "missing flag"
          in
          let level =
            match level with
            | Some level -> level
            | None -> fatal path 1 "missing level"
          in
          { path; flag; flag_line; level }
        | text -> (
          match words text with
          | [] -> read ~line:(line + 1) ~flag ~level
          | key :: values ->
            (match key with
            | "flag" ->
              if Option.is_some flag then fatal path line "duplicate key flag"
            | "level" ->
              if Option.is_some level then fatal path line "duplicate key level"
            | _ -> fatal path line "unknown key %s" key);
            let value =
              match values with
              | [value] when is_token value -> value
              | _ -> fatal path line "expected %s <token>" key
            in
            match key with
            | "flag" ->
              (match value with
              | "all" | "universe" | "optimizations" ->
                fatal path line "reserved flag name %s" value
              | _ -> ());
              read ~line:(line + 1) ~flag:(Some (value, line)) ~level
            | _ ->
              let level =
                match value with
                | "ai-reviewed" -> Ai_reviewed
                | "human-reviewed" -> Human_reviewed
                | _ -> fatal path line "unknown review level %s" value
              in
              read ~line:(line + 1) ~flag ~level:(Some level))
      in
      read ~line:1 ~flag:None ~level:None)

let registrations paths =
  let entries =
    List.map read_registration paths
    |> List.sort (fun left right -> String.compare left.flag right.flag)
  in
  let rec check_duplicates = function
    | [] | [_] -> ()
    | left :: (right :: _ as rest) ->
      if String.equal left.flag right.flag
      then
        fatal right.path right.flag_line
          "duplicate flag %s (also registered in %s)" right.flag left.path;
      check_duplicates rest
  in
  check_duplicates entries;
  entries

let constructor flag =
  (* Flag names contain neither underscores nor apostrophes, so this mapping
     is injective. The prefix also handles names beginning with a digit. *)
  "Feature_"
  ^ String.map (function '-' -> '_' | '.' -> '\'' | c -> c) flag

let level_constructor = function
  | Ai_reviewed -> "Ai_reviewed"
  | Human_reviewed -> "Human_reviewed"

let write_types channel entries =
  Printf.fprintf channel
    {|(* Generated by tools/gen_experimental_features.ml. Do not edit. *)

type review_level = Ai_reviewed | Human_reviewed

|};
  match entries with
  | [] -> Printf.fprintf channel "type t = |\n"
  | _ ->
    Printf.fprintf channel "type t =\n";
    List.iter
      (fun entry -> Printf.fprintf channel "  | %s\n" (constructor entry.flag))
      entries

let write_mapping channel entries ~name ~result_type ~value =
  Printf.fprintf channel "\nlet %s : t -> %s = function\n" name result_type;
  match entries with
  | [] -> Printf.fprintf channel "  | _ -> .\n"
  | _ ->
    List.iter
      (fun entry ->
        Printf.fprintf channel "  | %s -> %s\n" (constructor entry.flag)
          (value entry))
      entries

let write_implementation channel entries =
  write_types channel entries;
  Printf.fprintf channel "\nlet all : t list = [%s]\n"
    (String.concat "; "
       (List.map (fun entry -> constructor entry.flag) entries));
  write_mapping channel entries ~name:"flag_name" ~result_type:"string"
    ~value:(fun entry -> Printf.sprintf "%S" entry.flag);
  write_mapping channel entries ~name:"review_level" ~result_type:"review_level"
    ~value:(fun entry -> level_constructor entry.level)

let write_interface channel entries =
  write_types channel entries;
  Printf.fprintf channel
    {|
(** All registered features, ordered by flag name. *)
val all : t list

(** The flag suffix from SCRUTINY, without [-experimental-]. *)
val flag_name : t -> string

val review_level : t -> review_level
|}

let write_file path write entries =
  let channel = open_out path in
  Fun.protect
    ~finally:(fun () -> close_out channel)
    (fun () -> write channel entries)

let () =
  match Array.to_list Sys.argv with
  | _ :: implementation :: interface :: paths -> (
    try
      let entries = registrations paths in
      write_file implementation write_implementation entries;
      write_file interface write_interface entries
    with
    | Sys_error message ->
      prerr_endline message;
      exit 2)
  | _ ->
    Printf.eprintf "Usage: %s OUTPUT.ml OUTPUT.mli [SCRUTINY ...]\n"
      Sys.argv.(0);
    exit 2
