open! Simplify_import

(* High-level view of the workflow for simplification of let cont:
 *
 * +--------------------+           +--------------------+
 * | simplify_let_cont  |           | rebuild_let_cont   |
 * +--------------------+           +--------------------+
 *           |                                 ^
 *           | DOWN(body)             UP(body) |
 *           v                                 |
 * +--------------------+           +--------------------+
 * | after_downwards_   |           | prepare_to_        |
 * | traversal_of_body  |           | rebuild_body       |
 * +--------------------+           +--------------------+
 *           |                                 ^
 *           | DOWN(handlers)     UP(handlers) |
 *           v                                 |
 * +--------------------+           +--------------------+
 * | after_downwards_   |           | prepare_to_        |
 * | traversal_of_body_ |           | rebuild_handlers   |
 * | and_handlers       |           |                    |
 * +--------------------+           +--------------------+
 *           |                                 ^
 *           |       DOWN_TO_UP(global)        |
 *           +---------------------------------+
 *)

(* For each stage, the information received by this stage is of type
   stage_data. *)

type simplify_let_cont_data =
  { body : Expr.t;
    handlers : Original_handlers.t
  }

type after_downwards_traversal_of_body_data =
  { denv_for_join : DE.t;
    handlers : Original_handlers.t;
    lifted_constants_before_body : LCS.t
  }

type handler_after_downwards_traversal =
  { params : Bound_parameters.t;
    simplified_handler : Simplified_expr.t;
    is_exn_handler : bool;
    is_cold : bool;
    (* continuations_used is the set of which continuations from this block of
       mutually recursive continuations is used inside the handler *)
    continuations_used : Continuation.Set.t;
    unbox_decisions : Unbox_continuation_params.Decisions.t;
    extra_params_and_args : EPA.t
        (* These extra params and args are generated by the CSE and the
           continuation lifting process. *)
  }

type after_downwards_traversal_of_body_and_handlers_data =
  { after_downwards_traversal_of_body : after_downwards_traversal_of_body_data;
    cont_uses_env_after_body : CUE.t;
    (* used for specialization *)
    simplified_body : Simplified_expr.t;
    cont_uses_env : CUE.t;
    (* total cont uses env in body + handlers, including the uses of the
       continuations currently being bound *)
    at_unit_toplevel : bool;
    invariant_params : Bound_parameters.t;
    invariant_extra_params_and_args : EPA.t;
    handlers : handler_after_downwards_traversal Continuation.Map.t
  }

type rebuilt_handlers_group =
  | Recursive of
      { continuation_handlers : RE.Continuation_handler.t Continuation.Lmap.t;
        invariant_params : Bound_parameters.t
      }
  | Non_recursive of
      { cont : Continuation.t;
        handler : RE.Continuation_handler.t
      }

type 'a prepare_to_rebuild_body_data =
  { simplified_body : 'a;
    handlers_from_the_inside_to_the_outside : rebuilt_handlers_group list;
    uenv_of_subsequent_exprs : UE.t
  }

type rebuild_let_cont_data =
  { handlers_from_the_inside_to_the_outside : rebuilt_handlers_group list;
    uenv_of_subsequent_exprs : UE.t
  }

(* Helpers *)

let split_non_recursive_let_cont handler =
  let cont, body =
    Non_recursive_let_cont_handler.pattern_match handler ~f:(fun cont ~body ->
        cont, body)
  in
  let cont_handler = Non_recursive_let_cont_handler.handler handler in
  let is_exn_handler = CH.is_exn_handler cont_handler in
  let is_cold = CH.is_cold cont_handler in
  let params, handler =
    CH.pattern_match cont_handler ~f:(fun params ~handler -> params, handler)
  in
  ( body,
    Non_recursive_handler.create ~cont ~params ~handler
      ~lifted_params:Bound_parameters.empty ~lifted_free_vars:[] ~is_exn_handler
      ~is_cold )

let split_recursive_let_cont handlers =
  let invariant_params, body, rec_handlers =
    Recursive_let_cont_handlers.pattern_match handlers
      ~f:(fun ~invariant_params ~body rec_handlers ->
        invariant_params, body, rec_handlers)
  in
  assert (not (Continuation_handlers.contains_exn_handler rec_handlers));
  let handlers = Continuation_handlers.to_map rec_handlers in
  let continuation_handlers =
    Continuation.Lmap.map
      (fun handler ->
        let is_cold = CH.is_cold handler in
        CH.pattern_match handler ~f:(fun params ~handler ->
            One_recursive_handler.create ~params ~handler ~is_cold))
      handlers
  in
  body, invariant_params, continuation_handlers

let decide_param_usage_non_recursive ~handler ~art ~required_names
    ~removed_aliased ~exn_bucket param : Apply_cont_rewrite.used =
  (* The free_names computation is the reference here, because it records
     precisely what is actually used in the term being rebuilt. The required
     variables computed by the data_flow analysis can only be an over
     approximation of it here (given that some simplification/dead code
     elimination may have removed some uses on the way up). To make sure the
     data_flow analysis is correct (or rather than the pre-condition for its
     correctness are verified, i.e. that on the way down, the use constraints
     accumulated are an over-approximation of the actual use constraints), we
     check here that all actually-used variables were also marked as used by the
     data_flow analysis. *)
  let free_names = RE.free_names handler in
  let param_var = BP.var param in
  let is_used =
    match NO.count_variable_normal_mode free_names param_var with
    | Zero -> Option.equal Variable.equal exn_bucket (Some param_var)
    | One | More_than_one -> true
  in
  if is_used && not (Name.Set.mem (Name.var param_var) required_names)
  then
    Misc.fatal_errorf
      "The data_flow analysis marked the following param as not required, but \
       the free_names indicate it is actually used::@\n\
       %a@\n\
       free_names = %a@\n\
       handler: %a"
      BP.print param NO.print free_names (Rebuilt_expr.print art) handler;
  if is_used && Variable.Set.mem param_var removed_aliased
  then
    Misc.fatal_errorf
      "The alias analysis marked the following param as removed, but the \
       free_names indicate it is actually used:@\n\
       %a@\n\
       free_names = %a@\n\
       handler: %a"
      BP.print param NO.print free_names (Rebuilt_expr.print art) handler;
  if is_used then Used else Unused

let decide_param_usage_recursive ~required_names ~invariant_set ~removed_aliased
    param : Apply_cont_rewrite.used =
  if
    Name.Set.mem (BP.name param) required_names
    && not (Variable.Set.mem (BP.var param) removed_aliased)
  then
    if Bound_parameter.Set.mem param invariant_set
    then Used_as_invariant
    else Used
  else Unused

let extra_params_for_continuation_param_aliases cont uacc rewrite_ids =
  let Flow_types.Alias_result.{ continuation_parameters; aliases_kind; _ } =
    UA.continuation_param_aliases uacc
  in
  let required_extra_args =
    Continuation.Map.find cont continuation_parameters
  in
  (* We don't want to add the extra params and args according to the order of
     the Int_ids hash, because that is unstable and produces noise in fexpr
     dumps.

     Ideally, we'd want to create the parameters according to the binding times
     of the original variables, but currently binding times are not comparable
     across scopes, so we instead sort the extra args according to their name
     stamp, which should be a good enough approximation for now. *)
  let extra_args_for_aliases_sorted_by_stamp =
    Variable.Set.fold
      (fun var acc -> (Variable.name_stamp var, var) :: acc)
      required_extra_args.extra_args_for_aliases []
    |> List.sort (fun (stamp1, _) (stamp2, _) -> Int.compare stamp2 stamp1)
  in
  List.fold_left
    (fun epa (_stamp, var) ->
      let extra_args =
        Apply_cont_rewrite_id.Map.of_set
          (fun _id -> EPA.Extra_arg.Already_in_scope (Simple.var var))
          rewrite_ids
      in
      let var_duid = Flambda_debug_uid.none in
      (* CR sspies: Improve the debug UID propagation here in the future.
         Concretely, extra params can sometimes be generated and not user
         visible (e.g. create during unboxing), and sometimes can be
         user-visible, or at least aliases of user-visible variable (e.g. CSE,
         loop invariants, etc...). See #3967. *)
      let var_kind =
        Flambda_kind.With_subkind.anything (Variable.Map.find var aliases_kind)
      in
      EPA.add
        ~extra_param:(Bound_parameter.create var var_kind var_duid)
        ~extra_args epa ~invalids:Apply_cont_rewrite_id.Set.empty)
    EPA.empty extra_args_for_aliases_sorted_by_stamp

let add_extra_params_for_mutable_unboxing cont uacc extra_params_and_args =
  let Flow_types.Mutable_unboxing_result.{ additional_epa; _ } =
    UA.mutable_unboxing_result uacc
  in
  match Continuation.Map.find_or_null cont additional_epa with
  | Null -> extra_params_and_args
  | This additional_epa ->
    EPA.concat ~inner:extra_params_and_args ~outer:additional_epa

type behaviour =
  | Invalid
  | Shortcut_to of Continuation.t * Simple.t list
  | Unknown

let get_removed_aliased_params uacc cont =
  let param_aliases = UA.continuation_param_aliases uacc in
  let cont_params =
    Continuation.Map.find cont param_aliases.continuation_parameters
  in
  cont_params.removed_aliased_params_and_extra_params

let make_rewrite_for_recursive_continuation uacc ~cont ~is_cold
    ~original_invariant_params ~invariant_extra_params_and_args
    ~original_variant_params ~variant_extra_params_and_args ~rewrite_ids =
  (* Note: extra_params_and_args come from CSE & immutable unboxing *)
  let alias_epa =
    extra_params_for_continuation_param_aliases cont uacc rewrite_ids
  in
  let invariant_extra_params_and_args =
    EPA.concat ~inner:invariant_extra_params_and_args ~outer:alias_epa
  in
  let variant_extra_params_and_args =
    add_extra_params_for_mutable_unboxing cont uacc
      variant_extra_params_and_args
  in
  let required_names = UA.required_names uacc in
  let removed_aliased = get_removed_aliased_params uacc cont in
  let invariant_set =
    BP.Set.union
      (Bound_parameters.to_set original_invariant_params)
      (Bound_parameters.to_set
         (EPA.extra_params invariant_extra_params_and_args))
  in
  let decide_param_usage =
    decide_param_usage_recursive ~required_names ~invariant_set ~removed_aliased
  in
  let rewrite =
    Apply_cont_rewrite.create
      ~original_params:
        (Bound_parameters.append original_invariant_params
           original_variant_params)
      ~extra_params_and_args:
        (EPA.concat ~outer:invariant_extra_params_and_args
           ~inner:variant_extra_params_and_args)
      ~decide_param_usage
  in
  let invariant_params, variant_params =
    Apply_cont_rewrite.get_used_params rewrite
  in
  let params = Bound_parameters.append invariant_params variant_params in
  let uacc =
    UA.map_uenv uacc ~f:(fun uenv ->
        let uenv = UE.add_apply_cont_rewrite uenv cont rewrite in
        UE.add_non_inlinable_continuation ~is_cold
          (UA.are_rebuilding_terms uacc)
          uenv cont ~params ~handler:Unknown)
  in
  uacc

let rebuild_let_cont (data : rebuild_let_cont_data) ~after_rebuild body uacc =
  (* Here both the body and the handlers have been rebuilt. We only need to
     restore the cost metrics and name occurrences accumulators, rebuild all the
     let cont expressions, and call after_rebuild with the result and the new
     upwards accumulator. *)
  let rec rebuild_groups body uacc groups =
    match groups with
    | [] ->
      (* Everything has now been rebuilt.

         We restore the upwards environment of [uacc] so that out-of-scope
         continuation bindings do not end up in the accumulator. *)
      let uacc = UA.with_uenv uacc data.uenv_of_subsequent_exprs in
      after_rebuild body uacc
    | Non_recursive { cont; handler } :: groups ->
      let name_occurrences_body = RE.free_names body in
      let num_free_occurrences_of_cont_in_body =
        (* Note that this does not count uses in trap actions. If there are uses
           in trap actions, but [remove_let_cont_leaving_body] is [true] below,
           then this must be a case where the exception handler can be demoted
           to a normal handler. This will cause the trap actions to be
           erased. *)
        NO.count_continuation name_occurrences_body cont
      in
      let is_applied_with_traps =
        NO.continuation_is_applied_with_traps name_occurrences_body cont
      in
      let remove_let_cont_leaving_body =
        match num_free_occurrences_of_cont_in_body with
        | Zero -> true
        | One | More_than_one -> false
      in
      (* Having rebuilt both the body and handler, the [Let_cont] expression
         itself is rebuilt -- unless either the continuation had zero uses, in
         which case we're left with the body; or if the body is just an
         [Apply_cont] (with no trap action) of [cont], in which case we're left
         with the handler. *)
      let expr =
        if remove_let_cont_leaving_body
        then body
        else
          let remove_let_cont_leaving_handler =
            match RE.to_apply_cont body with
            | Some apply_cont -> (
              if
                not
                  (Continuation.equal cont (Apply_cont.continuation apply_cont))
              then false
              else
                match Apply_cont.args apply_cont with
                | [] -> Option.is_none (Apply_cont.trap_action apply_cont)
                | _ :: _ -> false)
            | None -> false
          in
          if remove_let_cont_leaving_handler
          then
            match RE.Continuation_handler.is_zero_arity_handler handler with
            | Some handler ->
              RE.notify_removed
                ~operation:(Cost_metrics.removed (RE.cost_metrics body))
                handler
            | None ->
              Misc.fatal_error
                "Arity mismatch between apply_cont and handler definition"
          else
            RE.create_non_recursive_let_cont'
              (UA.are_rebuilding_terms uacc)
              cont handler ~body ~num_free_occurrences_of_cont_in_body
              ~is_applied_with_traps
      in
      rebuild_groups expr uacc groups
    | Recursive { continuation_handlers; invariant_params } :: groups ->
      let expr =
        RE.create_recursive_let_cont
          (UA.are_rebuilding_terms uacc)
          ~invariant_params continuation_handlers ~body
      in
      rebuild_groups expr uacc groups
  in
  rebuild_groups body uacc data.handlers_from_the_inside_to_the_outside

let prepare_to_rebuild_body ~rebuild_body
    (data : _ prepare_to_rebuild_body_data) uacc ~after_rebuild =
  (* At this point all handlers have been rebuild and added to the upwards
     environment. All that we still need to do is to rebuild the body, and then
     rebuild the chain of let cont expressions once this is done. We reinit the
     name occurrences and cost metrics one last time to get precise information
     for those two in the body, we rebuild the body, and we pass on to the final
     stage for the reconstruction of the let cont expressions. *)
  let simplified_body = data.simplified_body in
  let data : rebuild_let_cont_data =
    { uenv_of_subsequent_exprs = data.uenv_of_subsequent_exprs;
      handlers_from_the_inside_to_the_outside =
        data.handlers_from_the_inside_to_the_outside
    }
  in
  rebuild_body simplified_body uacc ~after_rebuild:(fun body uacc ->
      rebuild_let_cont data ~after_rebuild body uacc)

let add_lets_around_handler ~bound_params cont uacc handler =
  (* Lifted constant should be placed first, before the aliases of the Flow
     analysis.

     Indeed, if a lifted constant uses a parameter that is aliased by the Flow
     analysis, we need the constant to use the aliased version, and thus be in
     scope of the alias. Otherwise, the lifted constant can keep alive some
     parameters that the Flow analysis aliased and has thus marked as
     deleted. *)
  let handler, uacc =
    Simplify_common.place_required_lifted_constants handler uacc
      ~bound_names:bound_params
  in
  let Flow_types.Alias_result.{ continuation_parameters; _ } =
    UA.continuation_param_aliases uacc
  in
  let continuation_parameters =
    try Continuation.Map.find cont continuation_parameters
    with Not_found ->
      Misc.fatal_errorf
        "Continuation %a not found in the continuation param aliases map from \
         the Flow Analysis results."
        Continuation.print cont
  in
  (* The [lets_to_introduce] rebind parameters that the alias analysis has
     removed from the continuation. These lets must be placed outside any lifted
     constants placed above, since such constants can reference the removed
     parameters, which are not bound anywhere else. Conversely, each let's
     defining expression is the parameter's canonical dominator, which must be
     in scope at the continuation's use sites, so it cannot be bound by the
     lifted constants placed inside. *)
  Variable.Lmap.fold
    (fun var bound_to (handler, uacc) ->
      let var_duid = Flambda_debug_uid.none in
      (* CR sspies: [var] can be derived/aliased from a user visible variable.
         If we can, it would be good to propagate debugging UIDs (or derived
         UIDs) here in the future. For now, we make due without. See #3967 *)
      let bound_pattern =
        Bound_pattern.singleton (Bound_var.create var var_duid Name_mode.normal)
      in
      let named = Named.create_simple bound_to in
      let handler, uacc =
        Expr_builder.create_let_binding uacc bound_pattern named
          ~free_names_of_defining_expr:(Simple.free_names bound_to)
          ~cost_metrics_of_defining_expr:Cost_metrics.zero ~body:handler
      in
      handler, uacc)
    continuation_parameters.lets_to_introduce (handler, uacc)

let add_phantom_params_bindings uacc handler new_phantom_params =
  let machine_width = UE.machine_width (UA.uenv uacc) in
  let new_phantom_param_bindings_outermost_first =
    List.map
      (fun param ->
        let param_var, param_uid = BP.var_and_uid param in
        let kind = K.With_subkind.kind (BP.kind param) in
        let var = Bound_var.create param_var param_uid Name_mode.phantom in
        let let_bound = Bound_pattern.singleton var in
        let prim = Flambda_primitive.(Nullary (Optimised_out kind)) in
        let named = Named.create_prim prim Debuginfo.none in
        let simplified_defining_expr =
          Simplified_named.create ~machine_width named
        in
        Simplified_named.Keep_binding
          { let_bound;
            simplified_defining_expr;
            original_defining_expr = Some named
          })
      (Bound_parameters.to_list new_phantom_params)
  in
  EB.make_new_let_bindings uacc ~body:handler
    ~bindings_outermost_first:new_phantom_param_bindings_outermost_first

let rebuild_single_non_recursive_handler ~rebuild_expr ~at_unit_toplevel:_
    ~is_single_inlinable_use ~original_invariant_params cont
    (handler_to_rebuild : Simplified_expr.simplified_handler) uacc k =
  let { Simplified_expr.is_exn_handler;
        is_cold;
        rewrite_ids;
        params;
        simplified_handler;
        extra_params_and_args;
        invariant_extra_params_and_args
      } =
    handler_to_rebuild
  in
  (* In case the continuation was previously recursive, we make sure not to
     forget the invariant original and extra params. *)
  let params = Bound_parameters.append original_invariant_params params in
  let extra_params_and_args =
    EPA.concat ~inner:invariant_extra_params_and_args
      ~outer:extra_params_and_args
  in
  rebuild_expr simplified_handler uacc ~after_rebuild:(fun handler uacc ->
      let extra_params_and_args =
        EPA.concat ~inner:extra_params_and_args
          ~outer:
            (extra_params_for_continuation_param_aliases cont uacc rewrite_ids)
        |> add_extra_params_for_mutable_unboxing cont uacc
      in
      (* The aliases added by the flow_analysis re-use the exact same variable,
         name and stamp as the original dominator variable, which can throw off
         the lifted constant placement analysis, so we exclude those from the
         names we consider for lifted constant placement. *)
      let bound_aliases =
        let Flow_types.Alias_result.{ continuation_parameters; _ } =
          UA.continuation_param_aliases uacc
        in
        let required_extra_args =
          Continuation.Map.find cont continuation_parameters
        in
        Name_occurrences.create_variables
          required_extra_args.extra_args_for_aliases Name_mode.normal
      in
      let bound_params =
        Name_occurrences.diff
          (Name_occurrences.union
             (Bound_parameters.free_names params)
             (Bound_parameters.free_names
                (Continuation_extra_params_and_args.extra_params
                   extra_params_and_args)))
          ~without:bound_aliases
      in
      let handler, uacc =
        add_lets_around_handler cont uacc handler ~bound_params
      in
      let exn_bucket =
        if is_exn_handler
        then
          Some (Bound_parameter.var (List.hd (Bound_parameters.to_list params)))
        else None
      in
      let removed_aliased = get_removed_aliased_params uacc cont in
      let decide_param_usage =
        decide_param_usage_non_recursive ~handler
          ~art:(UA.are_rebuilding_terms uacc)
          ~required_names:(UA.required_names uacc) ~removed_aliased ~exn_bucket
      in
      let rewrite =
        Apply_cont_rewrite.create ~original_params:params ~extra_params_and_args
          ~decide_param_usage
      in
      let invariant_params, params =
        Apply_cont_rewrite.get_used_params rewrite
      in
      if not (Bound_parameters.is_empty invariant_params)
      then
        Misc.fatal_errorf "Non-recursive continuation has invariant params: %a"
          Apply_cont_rewrite.print rewrite;
      let new_phantom_params =
        Bound_parameters.filter
          (fun param -> NO.mem_var (RE.free_names handler) (BP.var param))
          (Apply_cont_rewrite.get_unused_params rewrite)
      in
      let handler, uacc =
        add_phantom_params_bindings uacc handler new_phantom_params
      in
      (* Update the cold marker on the rebuilt handler according to the marker
         on the [let cont], so that it gets properly propagated if the
         continuation gets inlined. *)
      let handler = if is_cold then RE.mark_as_cold handler else handler in
      let cont_handler =
        RE.Continuation_handler.create params ~handler ~is_exn_handler
      in
      (* The parameters are removed from the free name information as they are
         no longer in scope. *)
      let free_names = RE.Continuation_handler.free_names cont_handler in
      let uacc =
        UA.map_uenv uacc ~f:(fun uenv ->
            UE.add_apply_cont_rewrite uenv cont rewrite)
      in
      let uenv = UA.uenv uacc in
      (* TODO move to its own function *)
      let uenv =
        (* CR : factor this out in a separate function ? *)
        if
          (* We must make the final decision now as to whether to inline this
             continuation or not; we can't wait until
             [Simplify_apply_cont.rebuild_apply_cont] because we need to decide
             sooner than that whether to keep the [Let_cont] (in order to keep
             free name sets correct). *)
          is_single_inlinable_use
        then (
          (* Note that [Continuation_uses] won't set [is_single_inlinable_use]
             if [cont] is an exception handler. *)
          assert (not is_exn_handler);
          (* We pass the parameters and the handler expression, rather than the
             [CH.t], to avoid re-opening the name abstraction. *)
          UE.add_linearly_used_inlinable_continuation uenv cont ~params ~handler)
        else
          let behaviour =
            (* CR-someday mshinwell: This could be replaced by a more
               sophisticated analysis, but for the moment we just use a simple
               syntactic check. *)
            if is_exn_handler
            then Unknown
            else
              match RE.to_apply_cont handler with
              | Some apply_cont -> (
                match Apply_cont.trap_action apply_cont with
                | Some _ -> Unknown
                | None ->
                  let args = Apply_cont.args apply_cont in
                  Shortcut_to (Apply_cont.continuation apply_cont, args))
              | None -> (
                if
                  RE.can_be_removed_as_invalid handler
                    (UA.are_rebuilding_terms uacc)
                then Invalid
                else
                  match
                    UE.find_unique_continuation_handler
                      (UA.are_rebuilding_terms uacc)
                      uenv ~params ~handler ~is_exn_handler
                      ~free_names_without_params:free_names
                  with
                  | Some (cont, args) -> Shortcut_to (cont, args)
                  | None -> Unknown)
          in
          match behaviour with
          | Invalid ->
            let arity = Bound_parameters.arity params in
            UE.add_invalid_continuation uenv cont arity
          | Shortcut_to (shortcut_to, args) ->
            UE.add_continuation_shortcut uenv cont ~params ~shortcut_to ~args
          | Unknown ->
            UE.add_non_inlinable_continuation ~is_cold:(RE.is_cold handler)
              (UA.are_rebuilding_terms uacc)
              uenv cont ~params
              ~handler:
                (Known
                   ( handler,
                     ~is_exn_handler,
                     ~free_names_without_params:free_names ))
      in
      let uacc = UA.with_uenv uacc uenv in
      k cont_handler uacc)

let rebuild_single_recursive_handler ~rebuild_expr cont
    (handler_to_rebuild : Simplified_expr.simplified_handler) uacc k =
  rebuild_expr handler_to_rebuild.simplified_handler uacc
    ~after_rebuild:(fun handler uacc ->
      let handler =
        if handler_to_rebuild.is_cold then RE.mark_as_cold handler else handler
      in
      let rewrite =
        match UE.find_apply_cont_rewrite (UA.uenv uacc) cont with
        | None ->
          Misc.fatal_errorf
            "An [Apply_cont_rewrite] for the recursive continuation %a should \
             have already been added"
            Continuation.print cont
        | Some rewrite -> rewrite
      in
      let free_names_of_handler = RE.free_names handler in
      let handler, uacc =
        add_lets_around_handler cont uacc handler
          ~bound_params:(Apply_cont_rewrite.all_params_free_names rewrite)
      in
      let new_phantom_params =
        Bound_parameters.filter
          (fun param -> NO.mem_var free_names_of_handler (BP.var param))
          (Apply_cont_rewrite.get_unused_params rewrite)
      in
      let handler, uacc =
        add_phantom_params_bindings uacc handler new_phantom_params
      in
      let invariant_params, variant_params =
        Apply_cont_rewrite.get_used_params rewrite
      in
      let cont_handler =
        RE.Continuation_handler.create variant_params ~handler
          ~is_exn_handler:false
      in
      k invariant_params cont_handler uacc)

let rec rebuild_continuation_handlers_loop ~rebuild_body ~rebuild_expr
    ~simplified_body ~uenv_of_subsequent_exprs ~at_unit_toplevel
    ~original_invariant_params ~invariant_extra_params uacc ~after_rebuild
    (groups_to_rebuild : Simplified_expr.simplified_handlers_group list)
    rebuilt_groups =
  match groups_to_rebuild with
  | [] ->
    let data : _ prepare_to_rebuild_body_data =
      { simplified_body;
        uenv_of_subsequent_exprs;
        handlers_from_the_inside_to_the_outside = rebuilt_groups
      }
    in
    prepare_to_rebuild_body ~rebuild_body data uacc ~after_rebuild
  | Non_recursive { cont; handler; is_single_inlinable_use }
    :: groups_to_rebuild ->
    rebuild_single_non_recursive_handler ~rebuild_expr ~at_unit_toplevel
      ~original_invariant_params ~is_single_inlinable_use cont handler uacc
      (fun rebuilt_handler uacc ->
        rebuild_continuation_handlers_loop ~rebuild_body ~rebuild_expr
          ~simplified_body ~uenv_of_subsequent_exprs ~at_unit_toplevel
          ~original_invariant_params ~invariant_extra_params uacc ~after_rebuild
          groups_to_rebuild
          (Non_recursive { cont; handler = rebuilt_handler } :: rebuilt_groups))
  | Recursive { simplified_continuation_handlers } :: groups_to_rebuild ->
    (* Common setup for recursive handlers: add rewrites; for now: always add
       params (ignore alias analysis) *)
    let uacc =
      Continuation.Map.fold
        (fun cont (handler : Simplified_expr.simplified_handler) uacc ->
          make_rewrite_for_recursive_continuation uacc ~cont
            ~is_cold:handler.is_cold ~original_invariant_params
            ~original_variant_params:handler.params
            ~invariant_extra_params_and_args:
              handler.invariant_extra_params_and_args
            ~variant_extra_params_and_args:handler.extra_params_and_args
            ~rewrite_ids:handler.rewrite_ids)
        simplified_continuation_handlers uacc
    in
    (* Rebuild all the handlers *)
    let rec loop uacc invariant_params remaining_handlers rebuilt_handlers k =
      match Continuation.Map.min_binding_opt remaining_handlers with
      | None -> k (Option.get invariant_params) rebuilt_handlers uacc
      | Some (cont, handler) ->
        let remaining_handlers =
          Continuation.Map.remove cont remaining_handlers
        in
        rebuild_single_recursive_handler ~rebuild_expr cont handler uacc
          (fun cont_invariant_params rebuilt_handler uacc ->
            let invariant_params =
              match invariant_params with
              | None -> Some cont_invariant_params
              | Some invariant_params ->
                if
                  not
                    (Bound_parameters.equal invariant_params
                       cont_invariant_params)
                then
                  Misc.fatal_errorf
                    "Inconsistent invariant params: invariant_params=%a@ \
                     cont_invariant_params=%a"
                    Bound_parameters.print invariant_params
                    Bound_parameters.print cont_invariant_params
                else Some invariant_params
            in
            loop uacc invariant_params remaining_handlers
              (Continuation.Lmap.add cont rebuilt_handler rebuilt_handlers)
              k)
    in
    loop uacc None simplified_continuation_handlers Continuation.Lmap.empty
      (fun invariant_params rebuilt_handlers uacc ->
        (* Add all rewrites and continue rebuilding *)
        rebuild_continuation_handlers_loop ~rebuild_body ~rebuild_expr
          ~simplified_body ~uenv_of_subsequent_exprs ~at_unit_toplevel
          ~original_invariant_params ~invariant_extra_params uacc ~after_rebuild
          groups_to_rebuild
          (Recursive
             { continuation_handlers = rebuilt_handlers; invariant_params }
          :: rebuilt_groups))

let prepare_to_rebuild_handlers ~rebuild_body ~rebuild_expr
    (data : Simplified_expr.simplified_let_cont_handlers) simplified_body uacc
    ~after_rebuild =
  (* Here we just returned from the global [down_to_up], which is asking us to
     rebuild the let cont. The flow analyses have been done, and we start to
     rebuild the expressions. As with the downward pass, we loop over each
     defined handler to rebuild it. As the handlers have been sorted by
     strongly-connected components, we must process the handlers group-by-group,
     and rebuild the groups from the outside to the inside. For each of these
     groups, we need to perform different steps depending on whether it is a
     mutually-recursive group or a single non-recursive handler.

     For mutually-recursive groups, we need to add the rewrites to the
     environment, and then rebuild the handlers, as the handlers might use
     themselves, so the rewrites need to be ready at that point. We can only use
     the dataflow information to compute which parameters are used and which are
     not, since we won't be able to remove parameters after the handlers have
     been rebuilt, since we can't rewrite them inside themselves.

     For a single non-recursive handler, we first rebuild the handler. This
     allows us to get precise information on the parameters which are used,
     which are then used to add the rewrites to the environment.

     In both cases, we add the handlers to the environment after rebuilding
     them, so that the environment is ready when rebuilding the remaining
     handlers. We also reset the name occurrences and the cost metrics before
     rebuilding each handler, so that we know the name occurrences and cost
     metrics corresponding to each handler when rebuilding later. *)
  let uenv_of_subsequent_exprs = UA.uenv uacc in
  rebuild_continuation_handlers_loop ~rebuild_body ~rebuild_expr
    ~simplified_body ~at_unit_toplevel:data.at_unit_toplevel
    ~original_invariant_params:data.original_invariant_params
    ~invariant_extra_params:data.invariant_extra_params
    ~uenv_of_subsequent_exprs uacc ~after_rebuild
    data.handlers_from_the_outside_to_the_inside []

let rebuild_let_cont ~rebuild_body ~rebuild_expr
    (simplified_let_cont, simplified_body) uacc ~after_rebuild =
  prepare_to_rebuild_handlers ~rebuild_body ~rebuild_expr simplified_let_cont
    simplified_body uacc ~after_rebuild

let get_uses (data : after_downwards_traversal_of_body_and_handlers_data) cont =
  match CUE.get_continuation_uses data.cont_uses_env cont with
  | None ->
    Misc.fatal_errorf
      "Uses of %a not found in \
       [after_downwards_traversal_of_body_and_handlers_data]@."
      Continuation.print cont
  | Some cont -> cont

let create_handler_to_rebuild ~machine_width
    (data : after_downwards_traversal_of_body_and_handlers_data) cont
    (handler : handler_after_downwards_traversal) :
    Simplified_expr.simplified_handler =
  (* See comment at the top of
     [after_downwards_travsersal_of_body_and_handlers]. *)
  let uses = get_uses data cont in
  let use_ids = Continuation_uses.get_use_ids uses in
  let invariant_extra_args =
    Apply_cont_rewrite_id.Map.of_set
      (fun rewrite_id ->
        match
          Apply_cont_rewrite_id.Map.find_or_null rewrite_id
            (EPA.extra_args data.invariant_extra_params_and_args)
        with
        | This extra_args -> extra_args
        | Null ->
          Or_invalid.Ok
            (List.map
               (fun param ->
                 EPA.Extra_arg.Already_in_scope
                   (Simple.var (Bound_parameter.var param)))
               (Bound_parameters.to_list
                  (EPA.extra_params data.invariant_extra_params_and_args))))
      use_ids
  in
  (* This completes the extra args for recursive uses of all invariant extra
     params. Note that these extra params come from unboxing of already
     invariant params, as well as continuation lifting (and CSE if/when it
     generates extra params for recursive continuations). *)
  let invariant_epa =
    EPA.replace_extra_args data.invariant_extra_params_and_args
      invariant_extra_args
  in
  let extra_params_and_args =
    let arg_types_by_use_id = Continuation_uses.get_arg_types_by_use_id uses in
    let _, arg_types_by_use_id =
      Misc.Stdlib.List.split_at
        (List.length (Bound_parameters.to_list data.invariant_params))
        arg_types_by_use_id
    in
    Unbox_continuation_params.compute_extra_params_and_args ~machine_width
      handler.unbox_decisions ~arg_types_by_use_id handler.extra_params_and_args
  in
  { params = handler.params;
    simplified_handler = handler.simplified_handler;
    is_exn_handler = handler.is_exn_handler;
    is_cold = handler.is_cold;
    extra_params_and_args;
    invariant_extra_params_and_args = invariant_epa;
    rewrite_ids = Continuation_uses.get_use_ids uses
  }

module SCC = Strongly_connected_components.Make (Continuation)

let sort_handlers data handlers =
  let handlers_graph =
    Continuation.Map.map
      (fun handler -> handler.continuations_used)
      data.handlers
  in
  let sorted_handlers_from_the_inside_to_the_outside =
    SCC.connected_components_sorted_from_roots_to_leaf handlers_graph
  in
  Array.fold_left
    (fun inner group ->
      let group : Simplified_expr.simplified_handlers_group =
        match (group : SCC.component) with
        | Has_loop conts ->
          let simplified_continuation_handlers =
            List.fold_left
              (fun group cont ->
                Continuation.Map.add cont
                  (Continuation.Map.find cont handlers)
                  group)
              Continuation.Map.empty conts
          in
          Recursive { simplified_continuation_handlers }
        | No_loop cont ->
          let handler : Simplified_expr.simplified_handler =
            Continuation.Map.find cont handlers
          in
          let is_single_inlinable_use =
            match Continuation_uses.get_uses (get_uses data cont) with
            | [] | _ :: _ :: _ -> false
            | [use] -> (
              match One_continuation_use.use_kind use with
              | Inlinable -> true
              | Non_inlinable _ -> false)
          in
          Non_recursive { cont; handler; is_single_inlinable_use }
      in
      group :: inner)
    [] sorted_handlers_from_the_inside_to_the_outside

let add_lifted_continuations denv (lifted_conts : Original_handlers.t list) =
  List.fold_left
    (fun denv (handlers : Original_handlers.t) ->
      match handlers with
      | Non_recursive { cont; lifted_free_vars = free_vars; is_exn_handler; _ }
        ->
        DE.add_lifted_continuation denv cont ~free_vars ~is_exn_handler
      | Recursive { lifted_free_vars = free_vars; continuation_handlers; _ } ->
        Continuation.Lmap.fold
          (fun cont _ denv ->
            DE.add_lifted_continuation denv cont ~free_vars
              ~is_exn_handler:false)
          continuation_handlers denv)
    denv lifted_conts

let lifted_free_var var debug_uid =
  Lifted_free_var.create
    (BP.create var (K.With_subkind.anything (Variable.kind var)) debug_uid)

let expr_of_generic_handler ~params (simplified_handler : SE.t) =
  (* Partial rebuild of a generic handler, used as a base for simplified the
     specialized handlers.

     This returns a tuple [expr, removed_operations, lifted_conts] where:

     - [expr] is the rebuilt generic handler, as a basic block (i.e. it does not
     contain any [let cont]s);

     - [removed_operations] contains the operations removed during the
     simplification of the generic handler, that will not be seen by the
     specialized traversals;

     - [lifted_conts] contains the [SE.lifted_let_cont] entries for the lifted
     continuations, with their lifted parameters (computed here).

     Note that the continuations in the switch of the rebuild handler already
     have lifted arguments: if the current environment already has lifted
     continuations, the lifted args have been added when simplifying the switch,
     and [expr_of_generic_handler] adds lifted args for the continuations lifted
     out of the one we are specializing. *)
  let add_lifted_args lifted_conts apply_cont =
    match
      Continuation.Map.find_opt (AC.continuation apply_cont) lifted_conts
    with
    | None -> apply_cont
    | Some (free_vars, ~is_exn_handler) ->
      let args = AC.args apply_cont in
      let lifted_args = List.map Lifted_free_var.simple free_vars in
      AC.update_args apply_cont
        ~args:
          (Lifted_free_var.place_lifted ~is_exn_handler ~lifted:lifted_args args)
  in
  let terminator lifted_conts =
    match simplified_handler.simplified_terminator with
    | Simplified_switch { arms; condition_dbg; scrutinee; _ } ->
      let arms =
        Target_ocaml_int.Map.map
          (fun (apply_cont, ~annotations, _, _, _) ->
            Switch_arm.create ~annotations
              (add_lifted_args lifted_conts apply_cont))
          arms
      in
      Expr.create_switch (Switch.create ~condition_dbg ~scrutinee ~arms)
    | Simplified_apply _ | Simplified_apply_cont _ | Simplified_invalid _ ->
      (* The decision to specialize is made when simplifying a switch. *)
      Misc.fatal_errorf
        "Unexpected terminator at the end of a handler being specialized:@ %a"
        SE.print simplified_handler
  in
  let rec rebuild rev_free_vars rev_phantom_vars lifted_conts
      (lets_and_let_conts : SE.simplified_lets_and_let_conts) =
    match lets_and_let_conts with
    | Simplified_terminator ->
      terminator lifted_conts, simplified_handler.removed_operations, []
    | Simplified_let
        ( { bindings_to_place; removed_operations; rewrite_id = _ },
          lets_and_let_conts ) ->
      let bindings =
        List.map
          (fun (binding : Simplified_named.binding_to_place) ->
            match binding with
            | Keep_binding
                { let_bound = Singleton bound_var; simplified_defining_expr; _ }
              ->
              ( bound_var,
                Simplified_named.to_named simplified_defining_expr.named )
            | Keep_binding { let_bound = Set_of_closures _ | Static _; _ }
            | Delete_binding _ ->
              (* CR bclement: consider specializing non-lifted sets of closures,
                 but this would require modelling them accurately in the lifting
                 cost (lifted sets of closures are already dealt with: they are
                 replaced with an alias binding).

                 Static consts can only appear at toplevel and we don't
                 specialize at toplevel. *)
              Misc.fatal_errorf
                "Unexpected binding in a handler being specialized:@ %a@ in@ %a"
                Simplified_named.print_binding_to_place binding SE.print
                simplified_handler)
          bindings_to_place
      in
      let rev_free_vars, rev_phantom_vars =
        List.fold_left
          (fun (rev_free_vars, rev_phantom_vars) (bound_var, _) ->
            if Name_mode.is_normal (Bound_var.name_mode bound_var)
            then
              ( lifted_free_var (Bound_var.var bound_var)
                  (Bound_var.debug_uid bound_var)
                :: rev_free_vars,
                rev_phantom_vars )
            else rev_free_vars, bound_var :: rev_phantom_vars)
          (rev_free_vars, rev_phantom_vars)
          bindings
      in
      let body, removed_operations_in_body, lifted_let_conts =
        rebuild rev_free_vars rev_phantom_vars lifted_conts lets_and_let_conts
      in
      let expr =
        List.fold_right
          (fun (bound_var, named) body ->
            Let.create
              (Bound_pattern.singleton bound_var)
              named ~body ~free_names_of_body:Unknown
            |> Expr.create_let)
          bindings body
      in
      ( expr,
        Removed_operations.( + ) removed_operations removed_operations_in_body,
        lifted_let_conts )
    | Lifted_let_cont ({ denv; handlers }, lets_and_let_conts) ->
      let free_vars = List.rev rev_free_vars in
      let lifted_conts =
        match handlers with
        | Non_recursive { cont; is_exn_handler; _ } ->
          Continuation.Map.add cont (free_vars, ~is_exn_handler) lifted_conts
        | Recursive { continuation_handlers; _ } ->
          Continuation.Lmap.fold
            (fun cont _ lifted_conts ->
              Continuation.Map.add cont
                (free_vars, ~is_exn_handler:false)
                lifted_conts)
            continuation_handlers lifted_conts
      in
      let body, removed_operations, lifted_let_conts =
        rebuild rev_free_vars rev_phantom_vars lifted_conts lets_and_let_conts
      in
      let lifted_let_cont : SE.lifted_let_cont =
        { denv;
          handlers =
            Original_handlers.add_params_to_lift handlers free_vars
              ~phantom_vars:(List.rev rev_phantom_vars)
        }
      in
      body, removed_operations, lifted_let_cont :: lifted_let_conts
    | Simplified_let_cont _ ->
      Misc.fatal_errorf
        "Unexpected non-lifted let cont in a handler being specialized:@ %a"
        SE.print simplified_handler
  in
  let rev_free_vars =
    List.rev_map Lifted_free_var.create (Bound_parameters.to_list params)
  in
  rebuild rev_free_vars [] Continuation.Map.empty
    simplified_handler.simplified_lets_and_let_conts

type generic_handler =
  { generic_params : Bound_parameters.t;
    generic_extra_params_and_args : EPA.t;
    generic_handler : Expr.t;
    generic_is_cold : bool
  }

(* CR pchambart/gbury: All of those functions don't need to be recursive, it
   would be nice to split some of them out (e.g. prepare_dacc_for_handlers). *)
let rec compute_specialized_continuation ~simplify_expr ~original_cont
    ~(generic : generic_handler) dacc data use k =
  let cont = Continuation.rename original_cont in
  (* The specialized handler starts from a fresh copy of the generic handler,
     with fresh params. The extra params of the generic handler become
     (non-unboxed) params of the specialized handler. *)
  let params = Bound_parameters.rename generic.generic_params in
  let params_renaming =
    Bound_parameters.renaming generic.generic_params ~guaranteed_fresh:params
  in
  let generic_extra_params =
    EPA.extra_params generic.generic_extra_params_and_args
  in
  let extra_params = Bound_parameters.rename generic_extra_params in
  let extra_params_renaming =
    Bound_parameters.renaming generic_extra_params
      ~guaranteed_fresh:extra_params
  in
  let renaming =
    (* The order of composition does not matter, since the params and the extra
       params are distinct. *)
    Renaming.compose ~first:params_renaming ~second:extra_params_renaming
  in
  let handler = Expr.apply_renaming generic.generic_handler renaming in
  let use_id = One_continuation_use.id use in
  let extra_args : _ Or_invalid.t =
    match
      Apply_cont_rewrite_id.Map.find_or_null use_id
        (EPA.extra_args generic.generic_extra_params_and_args)
    with
    | This extra_args -> extra_args
    | Null ->
      if Bound_parameters.is_empty extra_params
      then Ok []
      else
        Misc.fatal_errorf "No extra args for use %a of %a"
          Apply_cont_rewrite_id.print use_id Continuation.print original_cont
  in
  let extra_params_and_args_from_generic_handler =
    if Bound_parameters.is_empty extra_params
    then EPA.empty
    else
      EPA.replace_extra_args
        (EPA.init_with_params_only extra_params)
        (Apply_cont_rewrite_id.Map.singleton use_id extra_args)
  in
  let use_with_extra_args =
    let extra_arg_types =
      List.mapi
        (fun i param ->
          let kind = K.With_subkind.kind (Bound_parameter.kind param) in
          match extra_args with
          | Invalid -> T.bottom kind
          | Ok extra_args -> (
            match (List.nth extra_args i : EPA.Extra_arg.t) with
            | Already_in_scope simple -> T.alias_type_of kind simple
            | New_let_binding _ | New_let_binding_with_named_args _ ->
              T.unknown kind))
        (Bound_parameters.to_list extra_params)
    in
    One_continuation_use.create
      (One_continuation_use.use_kind use)
      ~env_at_use:(One_continuation_use.env_at_use use)
      use_id
      ~arg_types:(One_continuation_use.arg_types use @ extra_arg_types)
  in
  let arg_types_by_use_id =
    let uses = Continuation_uses.create cont (Bound_parameters.arity params) in
    let uses = Continuation_uses.add_use uses use in
    Continuation_uses.get_arg_types_by_use_id uses
  in
  let dacc, unbox_decisions, is_exn_handler, extra_params_and_args_from_join =
    prepare_dacc_for_handlers dacc
      ~env_at_fork:data.after_downwards_traversal_of_body.denv_for_join ~params
      ~extra_params ~lifted_params:Bound_parameters.empty ~lifted_free_vars:[]
      ~consts_lifted_after_fork:
        (LCS.diff
           data.after_downwards_traversal_of_body.lifted_constants_before_body
           (DA.get_lifted_constants dacc))
      ~is_recursive:false (Continuation.sort cont) None
      (* Exception handlers are not specialized; see comment in
         simplify_switch_expr.ml *)
      [use_with_extra_args]
      ~arg_types_by_use_id
  in
  let extra_params_and_args =
    EPA.concat ~outer:extra_params_and_args_from_generic_handler
      ~inner:extra_params_and_args_from_join
  in
  (* Set the adequate state for lifting. Note that this must be done **after**
     the call to {prepare_dacc_for_handlers} as that function can sometimes set
     some of these values for the generic case. The arguments of the lifted
     params have already been added to the uses of lifted continuations in the
     generic handler. *)
  let dacc =
    DA.with_are_lifting_conts dacc
      (Are_lifting_conts.no_lifting In_continuation_specialization)
    |> DA.map_denv ~f:DE.forget_lifted_continuations
  in
  simplify_handler ~simplify_expr ~is_recursive:false ~is_exn_handler ~params
    cont dacc handler ~invariant_params:Bound_parameters.empty
    (fun dacc simplified_handler cont_uses_env_in_handler ->
      let cont_uses_env =
        CUE.union data.cont_uses_env cont_uses_env_in_handler
      in
      (* create the new handler *)
      let rebuild =
        { params;
          simplified_handler;
          is_exn_handler;
          is_cold = generic.generic_is_cold;
          continuations_used = Continuation.Set.empty;
          (* this is only used for sorting mutually recursive continuation, so
             this does not matter for non-recursive continuations *)
          unbox_decisions;
          extra_params_and_args
        }
      in
      (* set things up so that uses of the specialized continuation (in the body
         of the let cont) are rewritten on the way up *)
      let dacc =
        DA.add_specialization dacc
          (One_continuation_use.id use)
          ~old:original_cont ~specialized:cont
      in
      let cont_uses_env =
        CUE.record_continuation cont_uses_env cont
          (Bound_parameters.arity params)
      in
      let data =
        { data with
          handlers = Continuation.Map.add cont rebuild data.handlers;
          cont_uses_env =
            CUE.add_continuation_use cont_uses_env cont
              (One_continuation_use.use_kind use)
              ~id:(One_continuation_use.id use)
              ~env_at_use:(One_continuation_use.env_at_use use)
              ~arg_types:(One_continuation_use.arg_types use)
        }
      in
      k dacc data)

and compute_specialized_continuation_handlers ~simplify_expr ~original_cont
    ~generic dacc data uses k =
  match uses with
  | [] -> k dacc data
  | use :: other_uses ->
    compute_specialized_continuation ~simplify_expr ~original_cont ~generic dacc
      data use (fun dacc data ->
        compute_specialized_continuation_handlers ~simplify_expr ~original_cont
          ~generic dacc data other_uses k)

and specialize_continuation_if_needed ~simplify_expr ~denv_for_join ~down_to_up
    dacc (data : after_downwards_traversal_of_body_and_handlers_data) =
  match Continuation.Map.get_singleton data.handlers with
  | Some (cont, handler)
    when Continuation.Set.mem cont (DA.continuations_to_specialize dacc) -> (
    if handler.is_exn_handler
    then
      (* see comment in simplify_switch_expr.ml *)
      Misc.fatal_errorf "Exception handler %a cannot be specialized"
        Continuation.print cont;
    (* At this point we have done a downwards traversal on the body and the
       generic handler. We do a partial rebuild of the generic handler, which we
       will use for the specialized per-use handlers. *)
    let generic_handler, removed_operations, lifted_conts =
      expr_of_generic_handler ~params:handler.params handler.simplified_handler
    in
    (* We need to record the arity of the lifted continuations now, because they
       will be used in the specialized handler, even though we haven't really
       seen their let-cont. Also, remove the uses of the generic continuation:
       they will be rewritten to uses of the appropriate specialized
       continuation. *)
    let cont_uses_env_after_body =
      List.fold_left
        (fun cont_uses_env_after_body
             ({ handlers; denv = _ } : SE.lifted_let_cont) ->
          CUE.record_continuation_arity cont_uses_env_after_body handlers)
        data.cont_uses_env_after_body lifted_conts
    in
    let cont_uses_env_after_body = CUE.remove cont_uses_env_after_body cont in
    let down_to_up =
      down_to_up_for_lifted_continuations ~simplify_expr ~denv_for_join
        ~lifted_constants_before_body:
          data.after_downwards_traversal_of_body.lifted_constants_before_body
        ~outer_lifted_conts:[] lifted_conts ~down_to_up
    in
    match CUE.get_continuation_uses data.cont_uses_env cont with
    | None ->
      Misc.fatal_errorf "No uses for continuation %a to be specialized"
        Continuation.print cont
    | Some uses -> (
      let extra_params_and_args =
        let arg_types_by_use_id =
          Continuation_uses.get_arg_types_by_use_id uses
        in
        Unbox_continuation_params.compute_extra_params_and_args
          ~machine_width:(DE.machine_width (DA.denv dacc))
          handler.unbox_decisions ~arg_types_by_use_id
          handler.extra_params_and_args
      in
      match Continuation_uses.get_uses uses with
      | [] | [_] ->
        Misc.fatal_errorf
          "Empty uses or single use for continuation %a to be specialized"
          Continuation.print cont
      | uses ->
        (* We keep the dacc after the generic handler, including the constants
           lifted in it, which the specialized handlers and the lifted
           continuations may refer to, except for the uses of continuations in
           the generic handler, which are discarded, as is the generic handler
           for the flow analysis. *)
        let dacc =
          DA.with_continuation_uses_env dacc
            ~cont_uses_env:cont_uses_env_after_body
          |> DA.map_flow_acc ~f:(Flow.Acc.forget_continuation cont)
        in
        (* The operations removed while simplifying the generic handler are
           counted once, along with those of the body of the let cont. *)
        let data =
          { data with
            handlers = Continuation.Map.empty;
            cont_uses_env = cont_uses_env_after_body;
            cont_uses_env_after_body;
            simplified_body =
              SE.notify_removed ~operation:removed_operations
                data.simplified_body
          }
        in
        let generic =
          { generic_params = handler.params;
            generic_extra_params_and_args = extra_params_and_args;
            generic_handler;
            generic_is_cold = handler.is_cold
          }
        in
        let previous_are_lifting_conts = DA.are_lifting_conts dacc in
        compute_specialized_continuation_handlers ~simplify_expr
          ~original_cont:cont ~generic dacc data uses (fun dacc data ->
            let dacc =
              DA.with_are_lifting_conts dacc previous_are_lifting_conts
            in
            after_downwards_traversal_of_body_and_handlers data ~down_to_up dacc)
      ))
  | _ -> after_downwards_traversal_of_body_and_handlers data ~down_to_up dacc

and after_downwards_traversal_of_body_and_handlers
    (data : after_downwards_traversal_of_body_and_handlers_data) ~down_to_up
    dacc =
  (* Here, we want to actually rebuild the let-cont, so we need to call the
     global [down_to_up] function. First however, we have to take care of
     several things:

     - We need to compute the extra params and args related to unboxed
     parameters. This could not be done earlier, as we might not have seen every
     use of the continuations (particularly in the recursive case) (done in the
     [create_handler_to_rebuild] function).

     - Now that we were able to compute the extra params and args, we add this
     information to the flow analysis, so that it can correctly compute all the
     information we need when going up.

     - We perform a strongly-connected components analysis of the continuations
     to be able to turn mutually-recursive continuations into several
     independant blocks of recursive or non-recursive continuations. In case one
     of those is non-recursive, we can check whether the continuation is
     inlinable if it is used a single time. *)
  (* We need to reset the [dacc.cont_uses_env] for the rest of the traversal.
     Here, [data.cont_uses_env] contains the total CUE for the body + handler,
     so we only need to remove the continuations that we bind from it to reset
     the [cont_uses_env] correctly. *)
  let cont_uses_env =
    Continuation.Map.fold
      (fun cont _ cont_uses_env -> CUE.remove cont_uses_env cont)
      data.handlers data.cont_uses_env
  in
  let dacc = DA.with_continuation_uses_env dacc ~cont_uses_env in
  let handlers =
    Continuation.Map.mapi
      (create_handler_to_rebuild
         ~machine_width:(DE.machine_width (DA.denv dacc))
         data)
      data.handlers
  in
  let dacc =
    DA.map_flow_acc dacc ~f:(fun flow_acc ->
        Continuation.Map.fold
          (fun cont (handler : Simplified_expr.simplified_handler) flow_acc ->
            Flow.Acc.add_extra_params_and_args cont
              (EPA.concat ~inner:handler.invariant_extra_params_and_args
                 ~outer:handler.extra_params_and_args)
              flow_acc)
          handlers flow_acc)
  in
  let handlers_from_the_outside_to_the_inside = sort_handlers data handlers in
  let simplified_body = data.simplified_body in
  let data : Simplified_expr.simplified_let_cont_handlers =
    { handlers_from_the_outside_to_the_inside;
      at_unit_toplevel = data.at_unit_toplevel;
      original_invariant_params = data.invariant_params;
      invariant_extra_params =
        EPA.extra_params data.invariant_extra_params_and_args
    }
  in
  down_to_up dacc (SE.simplified_let_cont data simplified_body)

and prepare_dacc_for_handlers dacc ~env_at_fork ~params
    ?(extra_params = Bound_parameters.empty) ~is_recursive
    ~consts_lifted_after_fork continuation_sort is_exn_handler_cont uses
    ~lifted_params ~lifted_free_vars ~arg_types_by_use_id =
  (* In the recursive case, [params] are actually the invariant params, as we
     prepare a common dacc for all handlers. If the continuation has been
     lifted, [params] include its lifted params, [lifted_params], for the free
     variables [lifted_free_vars].

     [extra_params] are additional params, after [params], which are
     joined like the others (the [arg_types] of the [uses] include them) but
     never unboxed ([arg_types_by_use_id] does not include them). *)
  (* CR gbury: Some of the lifted params need not be unboxed (the ones that come
     from continuation original parameters), but others may benefit from being
     unboxed, for example variables that are let-bound in a continuations's
     handler. We should look into whether it's actually useful, and try enabling
     unboxing for those (while avoiding re-unboxing parameters that have already
     been unboxed). *)
  let env_at_fork =
    DE.enter_set_of_handlers env_at_fork ~lifted_free_vars ~lifted_params
  in
  if debug ()
  then
    Format.eprintf "*** JOIN ***@\n%a@\n%a@." LCS.print consts_lifted_after_fork
      Bound_parameters.print params;
  let join_result =
    Join_points.compute_handler_env uses
      ~params:(Bound_parameters.append params extra_params)
      ~is_recursive ~env_at_fork ~consts_lifted_after_fork
  in
  let code_age_relation = TE.code_age_relation (DA.typing_env dacc) in
  let handler_env =
    DE.with_code_age_relation code_age_relation join_result.handler_env
    |> DE.bump_current_level_scope
  in
  let do_not_unbox () =
    Unbox_continuation_params.make_do_not_unbox_decisions params
  in
  let handler_env, unbox_decisions, is_exn_handler, dacc =
    match (continuation_sort : Continuation.Sort.t) with
    | Normal_or_exn when join_result.is_single_inlinable_use -> (
      match is_exn_handler_cont with
      | Some cont ->
        (* This should be prevented by [Simplify_apply_cont_expr]. *)
        Misc.fatal_errorf
          "Exception handlers should never be marked as [Inlinable]:@ %a"
          Continuation.print cont
      (* Don't try to unbox parameters of inlinable continuations, since the
         typing env still contains enough information to avoid re-reading the
         fields. *)
      | None ->
        let dacc =
          DA.with_are_lifting_conts dacc
            (Are_lifting_conts.no_lifting In_inlinable_continuation)
        in
        handler_env, do_not_unbox (), false, dacc)
    | Normal_or_exn | Define_root_symbol ->
      let dacc, is_exn_handler =
        match is_exn_handler_cont with
        | None -> dacc, false
        | Some cont ->
          if join_result.escapes
          then dacc, true
          else DA.demote_exn_handler dacc cont, false
      in
      if is_exn_handler
      then handler_env, do_not_unbox (), true, dacc
      else
        (* Unbox the parameters of the continuation if possible. Any such
           unboxing will induce a rewrite (or wrapper) on the application sites
           of the continuation. *)
        let param_types = TE.find_params (DE.typing_env handler_env) params in
        let handler_env, decisions =
          Unbox_continuation_params.make_decisions handler_env
            ~continuation_arg_types:(Non_recursive arg_types_by_use_id) params
            param_types
        in
        handler_env, decisions, false, dacc
    | Return | Toplevel_return -> (
      match is_exn_handler_cont with
      | Some cont ->
        (* This should be prevented by [Simplify_apply_cont_expr]. *)
        Misc.fatal_errorf
          "Exception handlers should never be marked as [Return] or \
           [Toplevel_return]:@ %a"
          Continuation.print cont
      | None -> handler_env, do_not_unbox (), false, dacc)
  in
  ( DA.with_denv dacc handler_env,
    unbox_decisions,
    is_exn_handler,
    join_result.extra_params_and_args )

and simplify_handler ~simplify_expr ~is_recursive ~is_exn_handler
    ~invariant_params ~params cont dacc handler k =
  let dacc =
    DA.with_continuation_uses_env dacc
      ~cont_uses_env:(CUE.reset_uses (DA.continuation_uses_env dacc))
  in
  let dacc =
    DA.map_flow_acc
      ~f:
        (Flow.Acc.enter_continuation cont ~recursive:is_recursive
           ~is_exn_handler
           (Bound_parameters.append invariant_params params))
      dacc
  in
  simplify_expr dacc handler ~down_to_up:(fun dacc simplified_handler ->
      let dacc = DA.map_flow_acc ~f:(Flow.Acc.exit_continuation cont) dacc in
      let cont_uses_env_in_handler = DA.continuation_uses_env dacc in
      let cont_uses_env_in_handler =
        if is_recursive
        then CUE.mark_non_inlinable cont_uses_env_in_handler
        else cont_uses_env_in_handler
      in
      k dacc simplified_handler cont_uses_env_in_handler)

and simplify_single_recursive_handler ~simplify_expr
    ~lifted_constants_before_body cont_uses_env_so_far ~invariant_params
    all_handlers_set denv_to_reset dacc cont
    ({ params; handler; is_cold } : One_recursive_handler.t) k =
  (* Here we perform the downwards traversal on a single handler.

     We also make unboxing decisions at this step, which are necessary to
     correctly simplify the handler using the unboxed parameters, but we delay
     the unboxing extra_params_and_args to later, when we will have seen all
     uses (needed for the recursive continuation handlers). *)
  let handler_env =
    assert (not (DE.at_unit_toplevel denv_to_reset));
    DE.add_parameters_with_unknown_types ~extra:false denv_to_reset params
  in
  let handler_env =
    if is_cold then DE.mark_as_cold handler_env else handler_env
  in
  let is_cold = DE.is_cold handler_env in
  let handler_env =
    DE.add_lifted_constant_state handler_env
      (LCS.diff lifted_constants_before_body (DA.get_lifted_constants dacc))
  in
  let code_age_relation = TE.code_age_relation (DA.typing_env dacc) in
  let handler_env = DE.with_code_age_relation code_age_relation handler_env in
  let handler_env, unbox_decisions, dacc =
    (* Unbox the parameters of the continuation if possible. Any such unboxing
       will induce a rewrite (or wrapper) on the application sites of the
       continuation; that rewrite will be comptued later, when we compute all
       the extra args and params. *)
    let param_types = TE.find_params (DE.typing_env handler_env) params in
    let handler_env, decisions =
      Unbox_continuation_params.make_decisions handler_env
        ~continuation_arg_types:Recursive params param_types
    in
    handler_env, decisions, dacc
  in
  let dacc = DA.with_denv dacc handler_env in
  simplify_handler ~simplify_expr ~is_recursive:true ~is_exn_handler:false
    ~params ~invariant_params cont dacc handler
    (fun dacc simplified_handler cont_uses_env_in_handler ->
      let cont_uses_env_so_far =
        CUE.union cont_uses_env_so_far cont_uses_env_in_handler
      in
      let continuations_used =
        Continuation.Set.inter all_handlers_set
          (CUE.all_continuations_used cont_uses_env_in_handler)
      in
      k dacc
        { params;
          simplified_handler;
          is_exn_handler = false;
          is_cold;
          continuations_used;
          unbox_decisions;
          extra_params_and_args = EPA.empty
        }
        cont_uses_env_so_far)

and simplify_recursive_handlers ~down_to_up ~data ~simplified_body
    ~previous_are_lifting_conts ~cont_uses_env_after_body ~invariant_params
    ~invariant_epa ~continuation_handlers ~simplify_expr ~all_conts_set
    ~common_denv =
  let rec loop cont_uses_env_so_far reachable_handlers_to_simplify
      simplified_handlers_set simplified_handlers dacc =
    (* This is the core loop to simplify all handlers defined by a recursive let
       cont. We loop over all handlers, each time taking the first handler that
       we have not yet processed and that has at least one use, until we have
       seen every handler that is reachable. *)
    (* CR-someday ncourant: this makes the order in which continuations are
       processed dependant on things like the name of the compilation unit
       (because it affects the order on [Continuation.t], and thus the element
       returned by [min_elt_opt]). *)
    match Continuation.Set.min_elt_opt reachable_handlers_to_simplify with
    | None ->
      (* all remaining_handlers are unreachable *)
      let data : after_downwards_traversal_of_body_and_handlers_data =
        { simplified_body;
          cont_uses_env_after_body;
          after_downwards_traversal_of_body = data;
          cont_uses_env = cont_uses_env_so_far;
          invariant_params;
          invariant_extra_params_and_args = invariant_epa;
          handlers = simplified_handlers;
          at_unit_toplevel = false
        }
      in
      let dacc = DA.with_are_lifting_conts dacc previous_are_lifting_conts in
      after_downwards_traversal_of_body_and_handlers data ~down_to_up dacc
    | Some cont ->
      let reachable_handlers_to_simplify =
        Continuation.Set.remove cont reachable_handlers_to_simplify
      in
      let handler = Continuation.Lmap.find cont continuation_handlers in
      simplify_single_recursive_handler ~simplify_expr ~invariant_params
        ~lifted_constants_before_body:data.lifted_constants_before_body
        cont_uses_env_so_far all_conts_set common_denv dacc cont handler
        (fun dacc rebuild cont_uses_env_so_far ->
          let simplified_handlers_set =
            Continuation.Set.add cont simplified_handlers_set
          in
          let reachable_handlers_to_simplify =
            Continuation.Set.union reachable_handlers_to_simplify
              (Continuation.Set.diff rebuild.continuations_used
                 simplified_handlers_set)
          in
          let simplified_handlers =
            Continuation.Map.add cont rebuild simplified_handlers
          in
          loop cont_uses_env_so_far reachable_handlers_to_simplify
            simplified_handlers_set simplified_handlers dacc)
  in
  loop

and simplify_handlers ~simplify_expr ~down_to_up ~denv_for_join ~simplified_body
    (data : after_downwards_traversal_of_body_data) dacc =
  (* In this case we have decided not to lift the continuation being let-bound
     outside of its context. So the remaining thing to do is setup the dacc, and
     later decide whether to lift the continuations defined inside the
     continuation being currently let-bound. *)
  let body_continuation_uses_env = DA.continuation_uses_env dacc in
  let denv = data.denv_for_join in
  let previous_are_lifting_conts = DA.are_lifting_conts dacc in
  match data.handlers with
  | Non_recursive
      { cont;
        params;
        lifted_params;
        lifted_free_vars;
        handler;
        is_exn_handler;
        is_cold
      } -> (
    match
      Continuation_uses_env.get_continuation_uses body_continuation_uses_env
        cont
    with
    | None ->
      (* Continuation unused, no need to traverse its handler *)
      let data : after_downwards_traversal_of_body_and_handlers_data =
        { simplified_body;
          cont_uses_env_after_body = body_continuation_uses_env;
          after_downwards_traversal_of_body = data;
          cont_uses_env = body_continuation_uses_env;
          invariant_params = Bound_parameters.empty;
          invariant_extra_params_and_args = EPA.empty;
          handlers = Continuation.Map.empty;
          at_unit_toplevel = false
        }
      in
      after_downwards_traversal_of_body_and_handlers data ~down_to_up dacc
    | Some uses ->
      let dacc =
        DA.with_are_lifting_conts dacc
          (Are_lifting_conts.think_about_lifting_out_of ~is_exn_handler cont
             uses)
      in
      let at_unit_toplevel =
        (* We try to show that [handler] postdominates [body] (which is done by
           showing that [body] can only return through [cont]) and that if
           [body] raises any exceptions then it only does so to toplevel. If
           this can be shown and we are currently at the toplevel of a
           compilation unit, the handler for the environment can remain marked
           as toplevel (and suitable for "let symbol" bindings); otherwise, it
           cannot. *)
        DE.at_unit_toplevel denv && (not is_exn_handler)
        && Continuation.Set.subset
             (CUE.all_continuations_used body_continuation_uses_env)
             (Continuation.Set.of_list
                [cont; DE.unit_toplevel_exn_continuation denv])
      in
      let denv = DE.set_at_unit_toplevel_state denv at_unit_toplevel in
      let denv = if is_cold then DE.mark_as_cold denv else denv in
      let is_cold = DE.is_cold denv in
      if debug () then Format.eprintf "%a@." Continuation.print cont;
      let dacc, unbox_decisions, is_exn_handler, extra_params_and_args =
        prepare_dacc_for_handlers dacc ~env_at_fork:denv ~params ~lifted_params
          ~lifted_free_vars
          ~consts_lifted_after_fork:
            (LCS.diff data.lifted_constants_before_body
               (DA.get_lifted_constants dacc))
          ~is_recursive:false (Continuation.sort cont)
          (if is_exn_handler then Some cont else None)
          (Continuation_uses.get_uses uses)
          ~arg_types_by_use_id:(Continuation_uses.get_arg_types_by_use_id uses)
      in
      simplify_handler ~simplify_expr ~is_recursive:false ~is_exn_handler
        ~params cont dacc handler ~invariant_params:Bound_parameters.empty
        (fun dacc simplified_handler cont_uses_env_in_handler ->
          let cont_uses_env_so_far =
            CUE.union body_continuation_uses_env cont_uses_env_in_handler
          in
          let continuations_used = Continuation.Set.empty in
          let rebuild =
            { params;
              simplified_handler;
              is_exn_handler;
              is_cold;
              continuations_used;
              unbox_decisions;
              extra_params_and_args
            }
          in
          let dacc =
            DA.with_are_lifting_conts dacc previous_are_lifting_conts
          in
          let data : after_downwards_traversal_of_body_and_handlers_data =
            { simplified_body;
              cont_uses_env_after_body = body_continuation_uses_env;
              after_downwards_traversal_of_body = data;
              cont_uses_env = cont_uses_env_so_far;
              invariant_params = Bound_parameters.empty;
              invariant_extra_params_and_args = EPA.empty;
              handlers = Continuation.Map.singleton cont rebuild;
              at_unit_toplevel
            }
          in
          specialize_continuation_if_needed ~simplify_expr ~denv_for_join
            ~down_to_up dacc data))
  | Recursive
      { continuation_handlers;
        invariant_params;
        lifted_params;
        lifted_free_vars
      } ->
    (* CR gbury: we currently do not lift any continuation out of a recursive
     * continuation. For instance it would be useful on the following example:
     * let rec f = function
     *   | A ->
     *     do_something...
     *     f B
     *   | B ->
     *     do_something
     *     f A
     * After loopify, we'll get a recursive continuation, and inlining/unrolling
     * the continuation would be beneficial, and require lifting some continuations
     * out of a recursive continuation.
     *)
    let dacc =
      DA.with_are_lifting_conts dacc
        (Are_lifting_conts.no_lifting In_recursive_continuation)
    in
    let denv = DE.set_at_unit_toplevel_state denv false in
    let all_conts_set =
      Continuation.Set.of_list @@ Continuation.Lmap.keys continuation_handlers
    in
    let used_handlers_in_body =
      Continuation.Set.inter all_conts_set
        (CUE.all_continuations_used body_continuation_uses_env)
    in
    let all_uses =
      List.filter_map
        (CUE.get_continuation_uses body_continuation_uses_env)
        (Continuation.Set.elements all_conts_set)
    in
    let arity = Bound_parameters.arity invariant_params in
    let arg_types_by_use_id =
      Continuation_uses.get_arg_types_by_use_id_for_invariant_params arity
        all_uses
    in
    let uses = List.concat_map Continuation_uses.get_uses all_uses in
    let dacc, unbox_decisions, is_exn_handler, extra_params_and_args =
      prepare_dacc_for_handlers dacc ~env_at_fork:denv ~params:invariant_params
        ~lifted_params ~lifted_free_vars ~is_recursive:true
        ~consts_lifted_after_fork:
          (LCS.diff data.lifted_constants_before_body
             (DA.get_lifted_constants dacc))
        (Normal_or_exn : Continuation.Sort.t)
        None uses ~arg_types_by_use_id
    in
    let machine_width = DE.machine_width denv in
    let invariant_epa =
      Unbox_continuation_params.compute_extra_params_and_args ~machine_width
        unbox_decisions extra_params_and_args ~arg_types_by_use_id
    in
    let common_denv = DA.denv dacc in
    assert (not is_exn_handler);
    simplify_recursive_handlers ~down_to_up ~data ~simplified_body
      ~previous_are_lifting_conts
      ~cont_uses_env_after_body:body_continuation_uses_env ~invariant_params
      ~invariant_epa ~continuation_handlers ~simplify_expr ~all_conts_set
      ~common_denv body_continuation_uses_env used_handlers_in_body
      Continuation.Set.empty Continuation.Map.empty dacc

and after_downwards_traversal_of_body ~simplify_expr ~down_to_up
    (data : after_downwards_traversal_of_body_data) dacc simplified_body =
  (* At this point, we have done the downwards traversal of the body, and we
     have two situations wrt to continuation lifting. *)
  let denv_for_join = data.denv_for_join in
  match DA.are_lifting_conts dacc with
  | Lifting_out_of { continuation = _ } ->
    (* In this case, we have decided to lift the continuations of the handler
       out of it (see [Simplify_switch_expr]): their let conts are recorded in
       the simplified handler, and simplified after it. *)
    down_to_up dacc
      (SE.lifted_let_cont ~denv:denv_for_join data.handlers simplified_body)
  | Not_lifting _ | Analyzing _ ->
    simplify_handlers data dacc ~simplify_expr ~down_to_up ~denv_for_join
      ~simplified_body

and down_to_up_for_lifted_continuations ~simplify_expr ~denv_for_join
    ~lifted_constants_before_body ~outer_lifted_conts lifted_conts ~down_to_up =
  match lifted_conts with
  | [] -> down_to_up
  | ({ denv; handlers } : SE.lifted_let_cont) :: other_lifted_handlers ->
    (* At this point, we are lifting a continuation k' with handler [handlers],
       out of a continuation k, and:

       - [denv_for_join] is the denv just before the letk for k

       - [denv] is the denv just before the letk for k'

       And we need to decide which parts of denv to use to simplify the handlers
       of k' after there are lifted out from the handler of k. *)
    let actual_denv = DE.denv_for_lifted_continuation ~denv_for_join ~denv in
    (* The handlers of k' can use the lifted continuations that were in scope
       where k' was defined: the ones lifted from the let conts around it, which
       precede it in the list, and its own continuations if it is recursive. *)
    let lifted_conts_in_scope = handlers :: outer_lifted_conts in
    let actual_denv =
      add_lifted_continuations actual_denv lifted_conts_in_scope
    in
    let data : after_downwards_traversal_of_body_data =
      { denv_for_join = actual_denv; handlers; lifted_constants_before_body }
    in
    let down_to_up =
      after_downwards_traversal_of_body ~simplify_expr data ~down_to_up
    in
    down_to_up_for_lifted_continuations ~simplify_expr ~denv_for_join
      ~lifted_constants_before_body ~outer_lifted_conts:lifted_conts_in_scope
      other_lifted_handlers ~down_to_up

let simplify_let_cont0 ~(simplify_expr : _ Simplify_common.expr_simplifier) dacc
    (data : simplify_let_cont_data) ~down_to_up =
  (* We begin to simplify a let cont by simplifying its body, so that we can see
     all external calls to the handler in the non-recursive case, and so that we
     can know the values of all invariant arguments in the recursive case. We
     reset the [continuation_uses_env] so we can have precise information on
     continuations called by the body. *)
  let denv_before_body = DA.denv dacc in
  (* About scopes: supposing we are at scope 'n' before the let-cont, we will:

     - use scope 'n + 2' to inspect the body

     - use scope 'n + 1' to perform the join of continuation uses

     - bump the scope of the env after join to get an env at scope 'n + 2'

     - we repeat this process for each lifted continuation, whose join will take
     place at level 'n + 1' (which is the level for denv_for_join), after which
     the scope will be bumped to `n + 2`, so that further lifted continuations
     can also perform their join at level `n + 1`. *)
  let denv_for_join = DE.increment_continuation_scope denv_before_body in
  let denv_for_body =
    DE.add_liftable_let_cont (DE.increment_continuation_scope denv_for_join)
  in
  let handlers = data.handlers in
  let dacc = DA.with_denv dacc denv_for_body in
  let cont_uses_env =
    CUE.record_continuation_arity (DA.continuation_uses_env dacc) handlers
  in
  let dacc = DA.with_continuation_uses_env dacc ~cont_uses_env in
  let body = data.body in
  let lifted_constants_before_body = DA.get_lifted_constants dacc in
  simplify_expr dacc body ~down_to_up:(fun dacc simplified_body ->
      let data : after_downwards_traversal_of_body_data =
        { denv_for_join; handlers; lifted_constants_before_body }
      in
      after_downwards_traversal_of_body ~simplify_expr data ~down_to_up dacc
        simplified_body)

let simplify_let_cont ~simplify_expr dacc let_cont ~down_to_up =
  (* This is the entry point to simplify a let cont expression. The only thing
     it does is to match all handlers to break the name abstraction, and then
     call [simplify_let_cont_stage1]. *)
  let body, handlers =
    match (let_cont : Let_cont.t) with
    | Non_recursive { handler; _ } ->
      let body, non_rec_handler = split_non_recursive_let_cont handler in
      let original_handlers =
        Original_handlers.create_non_recursive non_rec_handler
      in
      body, original_handlers
    | Recursive handlers ->
      let body, invariant_params, continuation_handlers =
        split_recursive_let_cont handlers
      in
      let original_handlers =
        Original_handlers.create_recursive ~invariant_params
          ~lifted_params:Bound_parameters.empty ~lifted_free_vars:[]
          ~continuation_handlers
      in
      body, original_handlers
  in
  simplify_let_cont0 ~simplify_expr dacc { body; handlers } ~down_to_up

let simplify_as_recursive_let_cont ~simplify_expr dacc (body, handlers)
    ~down_to_up =
  (* Loopify needs to simplify a recursive continuation, but knowing the unique
     id of the continuation and parameters being simplified, so this function
     allows to simplify a recursive let cont with the name abstraction already
     opened. *)
  let continuation_handlers =
    Continuation.Lmap.map
      (fun handler ->
        let is_cold = CH.is_cold handler in
        CH.pattern_match handler ~f:(fun params ~handler ->
            One_recursive_handler.create ~params ~handler ~is_cold))
      handlers
  in
  let data : simplify_let_cont_data =
    { body;
      handlers =
        Original_handlers.create_recursive
          ~invariant_params:Bound_parameters.empty
          ~lifted_params:Bound_parameters.empty ~lifted_free_vars:[]
          ~continuation_handlers
    }
  in
  simplify_let_cont0 ~simplify_expr dacc data ~down_to_up
