let get_target modname =
  let base = String.uncapitalize_ascii modname in
  if base = "stdlib" || base = "std_exit"
     || String.starts_with base ~prefix:"camlinternal"
  then base
  else "stdlib__" ^ String.capitalize_ascii base

let rename_file target =
  get_target (Filename.remove_extension target) ^ Filename.extension target

let rule ~ppf ~target ~exts ~src ~deps ~action =
  Printf.fprintf ppf
    "(rule\n  (targets %s)\n  (deps (:src %s) %s)\n  (action %s))\n\n"
    (String.concat " " (List.map (fun e -> target ^ "." ^ e) exts))
    src (String.concat " " deps)
    action

let copy_files ~ppf files =
  Printf.fprintf ppf
    "(copy_files %s)\n" files

let sprintf = Printf.sprintf
let fprintf = Printf.fprintf

module StrTbl = Hashtbl.Make (String)
module StrSet = Set.Make (String)

(* Parse a file of "key1: val1 val2 val3" lines.  A key may appear on
   several lines (e.g. the per-variant "codegen_variant" records); every
   occurrence is kept, in file order. *)
let parse_table filename : string list list StrTbl.t =
  let table = StrTbl.create 10 in
  let process_line s =
    match String.index_opt s ':' with
    | None -> failwith ("Malformed line: " ^ s)
    | Some i ->
       let key = String.sub s 0 i |> String.trim in
       let vals =
         String.sub s (i+1) (String.length s - (i+1))
         |> String.split_on_char ' '
         |> List.filter (fun s -> s <> "")
       in
       let prev = try StrTbl.find table key with Not_found -> [] in
       StrTbl.replace table key (prev @ [vals])
  in
  In_channel.with_open_text filename (fun ch ->
    while
      match input_line ch with
      | s -> process_line s; true
      | exception End_of_file -> false
    do () done);
  table

let rec trans_closure ~dst ~src s =
  match StrTbl.find dst s with
  | deps -> deps
  | exception Not_found ->
     let (_base, imm_deps) =
       try StrTbl.find src s with Not_found -> failwith s in
     let deps =
       let f dep acc = StrSet.union acc (trans_closure ~dst ~src dep) in
       StrSet.fold f imm_deps imm_deps in
     StrTbl.add dst s deps;
     deps

let stdlib_flags =
  "-nopervasives -directory stdlib -strict-sequence -g -absname \
   -extension runtime_metaprogramming -nostdlib -safe-string -strict-formats \
   -no-alias-deps -w +a-4-9-40-41-42-44-45-48-66-67-70 -w -221 -principal"

let pp_flags ~awk_dir ~target =
  if target = "stdlib"
  then sprintf " -pp \"awk -f %%{dep:%s/expand_module_aliases.awk}\"" awk_dir
  else ""

(* [variant] is [None] for the rules of the default tree, stdlib/build, and
   [Some (dir, flags)] for those of the tree of a codegen variant, of which
   only the .cmx rules are generated: [dir] is the name of the tree's
   directory and [flags] the variant's ocamlopt flags. *)
let gen_rule ~ppf ~tgt_file ~base ~deps ~variant =
  let ext, annot =
    match Filename.extension tgt_file with
    | ".cmo" -> `Cmo, true
    | ".cmi" -> `Cmi, true
    | ".cmx" -> `Cmx, false
    | s -> failwith ("Unexpected extension " ^ s)
  in
  let flags =
    if annot then
      stdlib_flags ^ " -bin-annot -bin-annot-occurrences -bin-annot-cms"
    else
      stdlib_flags
  in
  let src =
    match ext with
    | `Cmi -> base ^ ".mli"
    | `Cmx | `Cmo -> base ^ ".ml"
  in
  let target = get_target base in
  let flags = flags ^ pp_flags ~awk_dir:".." ~target in
  if ext <> `Cmo && Option.is_none variant then begin
    (* sys.ml is generated by configure from sys.ml.in and already handles
       its line directives *)
    if src = "sys.ml" then
      copy_files ~ppf ("../" ^ src)
    else
      Printf.fprintf ppf
        "(rule\n\
        \  (with-stdout-to %s\n\
        \    (progn (echo \"# 2 \\\"%s\\\"\\n\") (cat ../%s))))\n\n"
    src src src
  end;
  match ext with
  | `Cmi ->
     let action =
       sprintf "(run %%{exe:../../main_native.exe} %s -o %s.cmi -c %%{src})"
         flags target
     in
     rule ~ppf ~target ~exts:["cmi";"cmsi";"cmti"] ~src ~deps ~action
  | `Cmx ->
     (match variant with
      | None ->
         let action =
           sprintf "(run %%{exe:../../boot_ocamlopt.exe} %s -cmi-file %s.cmi \
                     %%{read-lines:../../ocamlopt_stdlib_flags.txt} \
                     -o %s.cmx -c %%{src})"
             flags target target
         in
         rule ~ppf ~target ~exts:["o";"cmx"] ~src ~deps ~action
      | Some (dir, variant_flags) ->
         (* A variant tree compiles the default tree's copy of the source,
            in the default tree's directory.  The path of the source is part
            of the symbols of anonymous functions (-absname) and of the
            debug information, and it must be the same in every tree: the
            trees of two variants that differ only in poll insertion have
            to define the same symbols and to have the same implementation
            CRCs (see Codegen_variant.selected_tree in
            utils/codegen_variant.mli).  A debugger then finds one source
            for every variant, too.  -nocwd keeps the default tree's own
            .cmx files out of the search path. *)
         let action =
           sprintf "(chdir ../build \
                     (run %%{exe:../../boot_ocamlopt.exe} %s %s -nocwd \
                      -I ../%s -cmi-file ../%s/%s.cmi \
                      %%{read-lines:../../ocamlopt_stdlib_flags.txt} \
                      -o ../%s/%s.cmx -c %%{src}))"
             variant_flags flags dir dir target dir target
         in
         rule ~ppf ~target ~exts:["o";"cmx"] ~src:("../build/" ^ src) ~deps
           ~action)
  | `Cmo ->
     let action =
       sprintf "(run %%{exe:../../main_native.exe} %s -cmi-file %s.cmi \
                                                   -o %s.cmo -c %%{src})"
         flags target target
     in
     rule ~ppf ~target ~exts:["cmo";"cms";"cmt"] ~src ~deps ~action

let settings_table = parse_table Sys.argv.(1)
let setting s =
  match StrTbl.find settings_table s with
  | [vals] -> vals
  | _ :: _ :: _ -> failwith ("Duplicated build_setting " ^ s)
  | [] | exception Not_found -> failwith ("Missing build_setting " ^ s)

(* All the value lines for a key that may legitimately appear on several
   lines (or not at all). *)
let multi_setting s =
  try StrTbl.find settings_table s with Not_found -> []

(* The per-variant build records written by Makefile.upstream, one line per
   NON-default codegen variant in the configure-computed list:
     "codegen_variant: <name>|<ocamlopt>|<cc>|<aspp>|<OCAMLPARAM>"
   gen.ml consumes the flag fields verbatim: the name->flag derivation
   lives in Makefile.codegen-variants (the Makefile-side encoding of
   utils/codegen_variant_name.ml's tables).  Because no fingerprint covers
   the runtime cc/aspp flags (and nothing else would catch OCAMLPARAM
   drift), every parsed record is asserted against the flags the linked
   copy of codegen_variant_name.ml derives for the name, failing
   generation when the two encoders have drifted.  Kept as functions:
   unconfigured trees have empty values for these keys, and only the code
   paths that need them may evaluate them. *)
type codegen_variant_record = {
  cv_name : Codegen_variant_name.t;
  cv_ocamlopt_flags : string list;
  cv_cc_flags : string list;
  cv_aspp_flags : string list;
}

let codegen_variant_records () =
  multi_setting "codegen_variant"
  |> List.map (fun vals ->
    let line = String.concat " " vals in
    match String.split_on_char '|' line with
    | [name; ocamlopt; cc; aspp; ocamlparam] ->
       let words s =
         String.split_on_char ' ' s |> List.filter (fun s -> s <> "")
       in
       let name = String.trim name in
       let cv_name =
         match Codegen_variant_name.of_string name with
         | Some n -> n
         | None ->
            failwith (sprintf "Invalid codegen variant name %S" name)
       in
       let check_drift column expected actual =
         if not (List.equal String.equal expected actual) then
           failwith
             (sprintf
                "codegen_variant record for %S: %s flags [%s] disagree \
                 with [%s] from utils/codegen_variant_name.ml; the tables \
                 in Makefile.codegen-variants have drifted from it"
                name column
                (String.concat " " actual)
                (String.concat " " expected))
       in
       check_drift "ocamlopt"
         (Codegen_variant_name.ocamlopt_flags cv_name) (words ocamlopt);
       check_drift "cc"
         (Codegen_variant_name.variant_cc_flags cv_name) (words cc);
       check_drift "aspp"
         (Codegen_variant_name.variant_aspp_flags cv_name) (words aspp);
       check_drift "OCAMLPARAM"
         [String.concat "," (Codegen_variant_name.ocamlparams cv_name)]
         [String.trim ocamlparam];
       { cv_name;
         cv_ocamlopt_flags = words ocamlopt;
         cv_cc_flags = words cc;
         cv_aspp_flags = words aspp }
    | _ -> failwith ("Malformed codegen_variant record: " ^ line))

let codegen_default_variant () =
  match setting "codegen_default_variant" with
  | [name] ->
     (match Codegen_variant_name.of_string name with
      | Some n -> n
      | None ->
         failwith (sprintf "Invalid codegen_default_variant %S" name))
  | v ->
     failwith
       (sprintf "codegen_default_variant should be a single name, got: %s"
          (String.concat " " v))

let module_deps_table filename =
  parse_table filename
  |> StrTbl.to_seq
  |> Seq.map (fun (tgt_file, deps_lines) ->
    let deps = List.concat deps_lines in
    let strip s =
      if String.starts_with s ~prefix:"./" then
        String.sub s 2 (String.length s - 2)
      else s
    in
    let tgt_file = strip tgt_file and deps = List.map strip deps in
    let basename = Filename.remove_extension tgt_file in
    let tgt_file =
      rename_file tgt_file and deps = List.map rename_file deps
    in
    tgt_file, (basename, StrSet.of_list deps))
  |> StrTbl.of_seq

let iter_module_deps table f =
  let trans_table = StrTbl.create 10 in
  table |> StrTbl.iter (fun tgt_file (base, _imm_deps) ->
    let deps =
      trans_closure ~src:table ~dst:trans_table tgt_file |> StrSet.to_list
    in
    f ~tgt_file ~base ~deps)

(* Generate rules to build the stdlib (only used in bootstrap build).

   [variant] selects which stdlib tree the rules build:
   - [`Base]: stdlib/build, the configure-default codegen mode.
   - [`Variant name]: the sibling stdlib/build_<name> tree serving the named
     NON-default codegen variant (absolute naming: build_fp is always the
     frame-pointer tree). Only the native artifacts are rebuilt, by
     boot_ocamlopt with the variant's per-axis ocamlopt flags (from the
     codegen_variant build-settings record) prepended to the stdlib flags,
     from the sources of stdlib/build (see gen_rule);
     the codegen-variant-agnostic byte artifacts (.cmi/.cmo/.cma/...) are
     copied from build/, and the variant's runtime archives (built by
     @runtime_variants; suffixed by the variant name's projection onto the
     runtime axes) are copied from runtime/, so that one variant tree is a
     complete stdlib root for compiling and linking in that mode. When the
     named variant is not in the configure-computed build list (it is the
     default, its axes do not exist yet, or codegen variants are disabled),
     only an empty alias is emitted, keeping every @stdlib_<name>
     well-defined. *)
(* [@inline never] [@local never]: this must stay the body of a function.
   All the calls are tail calls of the expression that ends this file, so
   the function would otherwise become a continuation of the module's
   initialization code, where the compiler stops on the body under
   -O3 -flambda2-match-in-match ("symbol is used but not defined", checked
   after Simplify). *)
let[@inline never] [@local never] write_stdlib_dune ~variant ppf =
  let alias_name =
    match variant with
    | `Base -> "stdlib"
    | `Variant name -> "stdlib_" ^ name
  in
  let record =
    match variant with
    | `Base -> None
    | `Variant name ->
       List.find_opt
         (fun r -> String.equal (Codegen_variant_name.to_string r.cv_name) name)
         (codegen_variant_records ())
  in
  let active =
    match variant with
    | `Base -> true
    | `Variant _ -> Option.is_some record
  in
  if not active then fprintf ppf "(alias (name %s))\n" alias_name else
  let extra_native_flags =
    match record with
    | None -> ""
    | Some r -> String.concat " " r.cv_ocamlopt_flags
  in
  let native_only = variant <> `Base in
  let rule_variant =
    match variant with
    | `Base -> None
    | `Variant name -> Some ("build_" ^ name, extra_native_flags)
  in
  let table = module_deps_table Sys.argv.(3) in
  iter_module_deps table (fun ~tgt_file ~base ~deps ->
    if (not native_only) || Filename.extension tgt_file = ".cmx" then
      gen_rule ~ppf ~tgt_file ~base ~deps ~variant:rule_variant);
  let modnames = setting "stdlib_modules" in
  let native_flags_prefix =
    match extra_native_flags with "" -> "" | extra -> extra ^ " "
  in
  let action =
    modnames
    |> List.map (fun m -> sprintf "%%{dep:%s.cmx}" (get_target m))
    |> String.concat " "
    |> sprintf "(run %%{exe:../../boot_ocamlopt.exe} %s-g -nostdlib -a \
                                                     -o stdlib.cmxa %s)"
         native_flags_prefix
  in
  rule ~ppf ~target:"stdlib" ~exts:["cmxa";"a"]
    ~src:(if native_only then "../build/stdlib.ml" else "stdlib.ml")
    ~deps:(modnames |> List.map (fun m -> get_target m ^ ".o"))
    ~action;
  if not native_only then begin
    let action =
      modnames
      |> List.map (fun m -> sprintf "%%{dep:%s.cmo}" (get_target m))
      |> String.concat " "
      |> sprintf "(run %%{exe:../../main_native.exe} -g -nostdlib -a \
                                                     -o stdlib.cma %s)"
    in
    rule ~ppf ~target:"stdlib" ~exts:["cma"] ~src:"stdlib.ml"
      ~deps:(modnames |> List.map (fun m -> get_target m ^ ".cmo"))
      ~action
  end;
  (* The runtime archives of the tree: those of the bytecode runtime, and
     the native ones of the tree's variant (suffixed as described in
     write_runtime_dune; "" for the default tree and for a variant that
     shares the default's archives).  No other archive of runtime/ may have
     a copy rule here: the tree is installed as it is found, with whatever
     an earlier build left in it, and an unsuffixed archive in a variant's
     tree would be the default variant's runtime. *)
  let codegen_suff =
    match record with
    | None -> ""
    | Some r ->
       Codegen_variant_name.runtime_archive_suffix r.cv_name
         ~default:(codegen_default_variant ())
  in
  let runtime_archives =
    [ "libcamlrun.a"; "libcamlrund.a"; "libcamlrun_pic.a";
      "libcamlrun_shared.so";
      "libasmrun" ^ codegen_suff ^ ".a";
      "libasmrund" ^ codegen_suff ^ ".a";
      "libasmrun_pic" ^ codegen_suff ^ ".a";
      "libasmrun_shared" ^ codegen_suff ^ ".so" ]
  in
  List.iter
    (fun archive -> copy_files ~ppf ("../../runtime/" ^ archive))
    runtime_archives;
  fprintf ppf "(alias (name %s) (deps %s))\n" alias_name
    (String.concat " " runtime_archives);
  copy_files ~ppf "../../Makefile.config";
  copy_files ~ppf "../dune_rules/ld.conf";
  if not native_only then
    fprintf ppf "%s\n" {|
  (rule (target runtime-launch-info) (action (copy ../runtime.info %{target})))
  (alias
    (name stdlib)
    (deps
       stdlib.cma stdlib.cmxa stdlib.a
       std_exit.cmo std_exit.o std_exit.cmx
       (glob_files *.{cmi,cmti,cmsi,cmo,cms,cmt,cmx})
       (glob_files caml/*.{h,tbl})
       Makefile.config runtime-launch-info ld.conf
       stdlib/META dynlink/dynlink.cmxa))
  |}
  else begin
    (* Byte artifacts and sources are codegen-variant-agnostic: copy them
       from the default tree. (.cmx/.o/.a/.cmxa are rebuilt with the variant
       flags above, from the default tree's .ml files.) *)
    copy_files ~ppf "../build/*.{cmi,cmti,cmsi,cmo,cms,cmt}";
    copy_files ~ppf "../build/*.{ml,mli}";
    copy_files ~ppf "../build/stdlib.cma";
    fprintf ppf "%s\n" {|
  (rule (target runtime-launch-info) (action (copy ../runtime.info %{target})))
  |};
    fprintf ppf
      "(alias\n\
      \  (name %s)\n\
      \  (deps\n\
      \     stdlib.cma stdlib.cmxa stdlib.a\n\
      \     std_exit.cmo std_exit.o std_exit.cmx\n\
      \     (glob_files *.{ml,mli,cmi,cmti,cmsi,cmo,cms,cmt,cmx})\n\
      \     (glob_files caml/*.{h,tbl})\n\
      \     Makefile.config runtime-launch-info ld.conf\n\
      \     dynlink/dynlink.cmxa))\n"
      alias_name
  end

let write_stdlib_jsir_sources_dune ppf =
  setting "stdlib_modules" @ ["std_exit"] |> List.iter (fun m ->
    ["ml"; "mli"] |> List.iter (fun ext ->
      let file = m ^ "." ^ ext in
      fprintf ppf
        "(rule (target %s) (action (copy %%{ocaml_where}/%s %%{target})))\n"
        file file))

type jsir_target =
  { program : string; (* the value of -target *)
    env_var : string; (* where ocamlopt finds [program] *)
    ext_suffix : string }

let jsir_targets =
  [ { program = "js_of_ocaml"; env_var = "OXCAML_JS_OF_OCAML";
      ext_suffix = "js" };
    { program = "wasm_of_ocaml"; env_var = "OXCAML_WASM_OF_OCAML";
      ext_suffix = "wasm" } ]

let write_stdlib_jsir_dune_for_target ppf jsir_target =
  let src_dir = "../src" and stdlib_dir = "../../stdlib" in
  let ext base = base ^ "-" ^ jsir_target.ext_suffix in
  let run_ocamlopt args =
    sprintf "(setenv %s %%{bin:%s} (run %%{ocamlopt} -target %s %s))"
      jsir_target.env_var jsir_target.program jsir_target.program args
  in
  let installed file = sprintf "%%{ocaml_where}/%s" file in
  let table = module_deps_table Sys.argv.(3) in
  iter_module_deps table (fun ~tgt_file ~base ~deps ->
    if Filename.extension tgt_file = ".cmx" then begin
      let target = get_target base in
      let src = sprintf "%s/%s.ml" src_dir base in
      let deps =
        installed (target ^ ".cmi")
        :: List.map (fun dep ->
             match Filename.extension dep with
             | ".cmx" -> Filename.remove_extension dep ^ "." ^ ext "cmx"
             | ".cmi" -> installed dep
             | s -> failwith ("Unexpected extension " ^ s))
             deps
        |> StrSet.of_list |> StrSet.to_list
      in
      (* -S keeps the JSIR of the unit (.cm-jsir-js or .cm-jsir-wasm), with
         which it can also be linked with -link-jsir. *)
      let action =
        run_ocamlopt
          (sprintf
             "%s%s -S -I %%{ocaml_where} -cmi-file %s -o %s.%s -c %%{src}"
             stdlib_flags (pp_flags ~awk_dir:stdlib_dir ~target)
             (installed (target ^ ".cmi")) target (ext "cmx"))
      in
      rule ~ppf ~target ~exts:[ext "cmx"; ext "cmo"; ext "cm-jsir"] ~src ~deps
        ~action
    end);
  let modnames = setting "stdlib_modules" in
  let targets = List.map get_target modnames in
  (* The library is created twice: for separate compilation (.cma-js or
     .cma-wasm) and for -link-jsir (.cma-jsir-js or .cma-jsir-wasm, from the
     JSIR of the units). Both write the same .cmxa-js or .cmxa-wasm. *)
  let action =
    let archive flags =
      targets
      |> List.map (fun t -> sprintf "%%{dep:%s.%s}" t (ext "cmx"))
      |> String.concat " "
      |> sprintf "-g -nostdlib%s -a -o stdlib.%s %s" flags (ext "cmxa")
      |> run_ocamlopt
    in
    sprintf "(progn %s %s)" (archive "") (archive " -link-jsir")
  in
  rule ~ppf ~target:"stdlib" ~exts:[ext "cmxa"; ext "cma"; ext "cma-jsir"]
    ~src:(sprintf "%s/stdlib.ml" src_dir)
    ~deps:
      (List.concat_map
         (fun t -> [t ^ "." ^ ext "cmo"; t ^ "." ^ ext "cm-jsir"])
         targets)
    ~action

let write_stdlib_jsir_dune ppf =
  List.iter (write_stdlib_jsir_dune_for_target ppf) jsir_targets

