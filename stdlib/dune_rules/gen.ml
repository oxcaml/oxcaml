let get_target modname =
  let base = String.uncapitalize_ascii modname in
  if base = "stdlib" || base = "std_exit"
     || String.starts_with base ~prefix:"camlinternal"
  then base
  else "stdlib__" ^ String.capitalize_ascii base

let rename_file target =
  get_target (Filename.remove_extension target) ^ Filename.extension target

let rule ~ppf ~target ~exts ~src ~deps ~action =
  Printf.fprintf ppf
    "(rule\n  (targets %s)\n  (deps (:src %s) %s)\n  (action %s))\n\n"
    (String.concat " " (List.map (fun e -> target ^ "." ^ e) exts))
    src (String.concat " " deps)
    action

let copy_files ~ppf files =
  Printf.fprintf ppf
    "(copy_files %s)\n" files

let sprintf = Printf.sprintf
let fprintf = Printf.fprintf

module StrTbl = Hashtbl.Make (String)
module StrSet = Set.Make (String)

(* Parse a file of "key1: val1 val2 val3" lines *)
let parse_table filename : string list StrTbl.t =
  let table = StrTbl.create 10 in
  let process_line s =
    match String.index_opt s ':' with
    | None -> failwith ("Malformed line: " ^ s)
    | Some i ->
       let key = String.sub s 0 i |> String.trim in
       let vals =
         String.sub s (i+1) (String.length s - (i+1))
         |> String.split_on_char ' '
         |> List.filter (fun s -> s <> "")
       in
       StrTbl.replace table key vals
  in
  In_channel.with_open_text filename (fun ch ->
    while
      match input_line ch with
      | s -> process_line s; true
      | exception End_of_file -> false
    do () done);
  table

let rec trans_closure ~dst ~src s =
  match StrTbl.find dst s with
  | deps -> deps
  | exception Not_found ->
     let (_base, imm_deps) =
       try StrTbl.find src s with Not_found -> failwith s in
     let deps =
       let f dep acc = StrSet.union acc (trans_closure ~dst ~src dep) in
       StrSet.fold f imm_deps imm_deps in
     StrTbl.add dst s deps;
     deps

let stdlib_flags =
  "-nopervasives -directory stdlib -strict-sequence -g -absname \
   -extension runtime_metaprogramming -nostdlib -safe-string -strict-formats \
   -no-alias-deps -w +a-4-9-40-41-42-44-45-48-66-67-70 -w -221 -principal"

let pp_flags ~awk_dir ~target =
  if target = "stdlib"
  then sprintf " -pp \"awk -f %%{dep:%s/expand_module_aliases.awk}\"" awk_dir
  else ""

let gen_rule ~ppf ~tgt_file ~base ~deps ~extra_native_flags =
  let ext, annot =
    match Filename.extension tgt_file with
    | ".cmo" -> `Cmo, true
    | ".cmi" -> `Cmi, true
    | ".cmx" -> `Cmx, false
    | s -> failwith ("Unexpected extension " ^ s)
  in
  let flags =
    if annot then
      stdlib_flags ^ " -bin-annot -bin-annot-occurrences -bin-annot-cms"
    else
      stdlib_flags
  in
  let src =
    match ext with
    | `Cmi -> base ^ ".mli"
    | `Cmx | `Cmo -> base ^ ".ml"
  in
  let target = get_target base in
  let flags = flags ^ pp_flags ~awk_dir:".." ~target in
  if ext <> `Cmo then begin
    (* sys.ml is generated by configure from sys.ml.in and already handles
       its line directives *)
    if src = "sys.ml" then
      copy_files ~ppf ("../" ^ src)
    else
      Printf.fprintf ppf
        "(rule\n\
        \  (with-stdout-to %s\n\
        \    (progn (echo \"# 2 \\\"%s\\\"\\n\") (cat ../%s))))\n\n"
    src src src
  end;
  match ext with
  | `Cmi ->
     let action =
       sprintf "(run %%{exe:../../main_native.exe} %s -o %s.cmi -c %%{src})"
         flags target
     in
     rule ~ppf ~target ~exts:["cmi";"cmsi";"cmti"] ~src ~deps ~action
  | `Cmx ->
     let flags =
       match extra_native_flags with
       | "" -> flags
       | extra -> extra ^ " " ^ flags
     in
     let action =
       sprintf "(run %%{exe:../../boot_ocamlopt.exe} %s -cmi-file %s.cmi \
                 %%{read-lines:../../ocamlopt_stdlib_flags.txt} \
                 -o %s.cmx -c %%{src})"
         flags target target
     in
     rule ~ppf ~target ~exts:["o";"cmx"] ~src ~deps ~action
  | `Cmo ->
     let action =
       sprintf "(run %%{exe:../../main_native.exe} %s -cmi-file %s.cmi \
                                                   -o %s.cmo -c %%{src})"
         flags target target
     in
     rule ~ppf ~target ~exts:["cmo";"cms";"cmt"] ~src ~deps ~action

let settings_table = parse_table Sys.argv.(1)
let setting s =
  try StrTbl.find settings_table s
  with Not_found -> failwith ("Missing build_setting " ^ s)

let module_deps_table filename =
  parse_table filename
  |> StrTbl.to_seq
  |> Seq.map (fun (tgt_file, deps) ->
    let strip s =
      if String.starts_with s ~prefix:"./" then
        String.sub s 2 (String.length s - 2)
      else s
    in
    let tgt_file = strip tgt_file and deps = List.map strip deps in
    let basename = Filename.remove_extension tgt_file in
    let tgt_file =
      rename_file tgt_file and deps = List.map rename_file deps
    in
    tgt_file, (basename, StrSet.of_list deps))
  |> StrTbl.of_seq

let iter_module_deps table f =
  let trans_table = StrTbl.create 10 in
  table |> StrTbl.iter (fun tgt_file (base, _imm_deps) ->
    let deps =
      trans_closure ~src:table ~dst:trans_table tgt_file |> StrSet.to_list
    in
    f ~tgt_file ~base ~deps)

(* Kept as a function: unconfigured trees have empty values for these keys,
   and only the code paths that need them may evaluate them. *)
let bool_setting key =
  match setting key with
  | ["true"] -> true
  | ["false"] -> false
  | [] -> false (* an unconfigured tree has no value *)
  | v ->
     failwith
       (sprintf "Setting %s should be true or false, got: %s"
          key (String.concat " " v))

(* Generate rules to build the stdlib (only used in bootstrap build).

   [variant] selects which stdlib tree the rules build:
   - [`Base]: stdlib/build, the configure-default codegen mode.
   - [`Fp] / [`Base_variant]: the sibling stdlib/build_fp / build_base trees,
     which serve the NON-default frame-pointer mode (absolute naming: build_fp
     is always the frame-pointer tree). Only the native artifacts are rebuilt,
     by boot_ocamlopt with -frame-pointers / -no-frame-pointers prepended to
     the stdlib flags; the FP-agnostic byte artifacts (.cmi/.cmo/.cma/...)
     are copied from build/, and the matching codegen-variant runtime
     archives (libasmrun*_fp.* / *_base.*, built by @runtime_variants) are
     copied from runtime/, so that one variant tree is a complete stdlib
     root for compiling and linking in that mode. When the requested mode IS
     the configure default, or codegen variants are disabled, only an empty
     alias is emitted, keeping @stdlib_fp / @stdlib_base well-defined. *)
let write_stdlib_dune ~variant ppf =
  let alias_name =
    match variant with
    | `Base -> "stdlib"
    | `Fp -> "stdlib_fp"
    | `Base_variant -> "stdlib_base"
  in
  let active =
    match variant with
    | `Base -> true
    | `Fp ->
       bool_setting "build_codegen_variants"
       && not (bool_setting "codegen_default_fp")
    | `Base_variant ->
       bool_setting "build_codegen_variants"
       && bool_setting "codegen_default_fp"
  in
  if not active then fprintf ppf "(alias (name %s))\n" alias_name else
  let extra_native_flags =
    match variant with
    | `Base -> ""
    | `Fp -> "-frame-pointers"
    | `Base_variant -> "-no-frame-pointers"
  in
  let native_only = variant <> `Base in
  let table = module_deps_table Sys.argv.(3) in
  iter_module_deps table (fun ~tgt_file ~base ~deps ->
    if (not native_only) || Filename.extension tgt_file = ".cmx" then
      gen_rule ~ppf ~tgt_file ~base ~deps ~extra_native_flags);
  let modnames = setting "stdlib_modules" in
  let native_flags_prefix =
    match extra_native_flags with "" -> "" | extra -> extra ^ " "
  in
  let action =
    modnames
    |> List.map (fun m -> sprintf "%%{dep:%s.cmx}" (get_target m))
    |> String.concat " "
    |> sprintf "(run %%{exe:../../boot_ocamlopt.exe} %s-g -nostdlib -a \
                                                     -o stdlib.cmxa %s)"
         native_flags_prefix
  in
  rule ~ppf ~target:"stdlib" ~exts:["cmxa";"a"] ~src:"stdlib.ml"
    ~deps:(modnames |> List.map (fun m -> get_target m ^ ".o"))
    ~action;
  if not native_only then begin
    let action =
      modnames
      |> List.map (fun m -> sprintf "%%{dep:%s.cmo}" (get_target m))
      |> String.concat " "
      |> sprintf "(run %%{exe:../../main_native.exe} -g -nostdlib -a \
                                                     -o stdlib.cma %s)"
    in
    rule ~ppf ~target:"stdlib" ~exts:["cma"] ~src:"stdlib.ml"
      ~deps:(modnames |> List.map (fun m -> get_target m ^ ".cmo"))
      ~action
  end;
  (* The runtime archives of the tree: those of the bytecode runtime, and
     the native ones of the tree's variant (suffixed as described in
     write_runtime_dune; "" for the default tree and for a variant that
     shares the default's archives).  No other archive of runtime/ may have
     a copy rule here: the tree is installed as it is found, with whatever
     an earlier build left in it, and an unsuffixed archive in a variant's
     tree would be the default variant's runtime. *)
  let codegen_suff =
    match variant with
    | `Base -> ""
    | `Fp -> "_fp"
    | `Base_variant -> "_base"
  in
  let runtime_archives =
    [ "libcamlrun.a"; "libcamlrund.a"; "libcamlrun_pic.a";
      "libcamlrun_shared.so";
      "libasmrun" ^ codegen_suff ^ ".a";
      "libasmrund" ^ codegen_suff ^ ".a";
      "libasmrun_pic" ^ codegen_suff ^ ".a";
      "libasmrun_shared" ^ codegen_suff ^ ".so" ]
  in
  List.iter
    (fun archive -> copy_files ~ppf ("../../runtime/" ^ archive))
    runtime_archives;
  fprintf ppf "(alias (name %s) (deps %s))\n" alias_name
    (String.concat " " runtime_archives);
  copy_files ~ppf "../../Makefile.config";
  copy_files ~ppf "../dune_rules/ld.conf";
  if not native_only then
    fprintf ppf "%s\n" {|
  (rule (target runtime-launch-info) (action (copy ../runtime.info %{target})))
  (alias
    (name stdlib)
    (deps
       stdlib.cma stdlib.cmxa stdlib.a
       std_exit.cmo std_exit.o std_exit.cmx
       (glob_files *.{cmi,cmti,cmsi,cmo,cms,cmt,cmx})
       (glob_files caml/*.{h,tbl})
       Makefile.config runtime-launch-info ld.conf
       stdlib/META dynlink/dynlink.cmxa))
  |}
  else begin
    (* Byte artifacts are FP-agnostic: copy them from the default tree.
       (.ml files are regenerated locally as inputs of the .cmx rules;
       .cmx/.o/.a/.cmxa are rebuilt with the variant flags above.) *)
    copy_files ~ppf "../build/*.{cmi,cmti,cmsi,cmo,cms,cmt}";
    copy_files ~ppf "../build/*.mli";
    copy_files ~ppf "../build/stdlib.cma";
    fprintf ppf "%s\n" {|
  (rule (target runtime-launch-info) (action (copy ../runtime.info %{target})))
  |};
    fprintf ppf
      "(alias\n\
      \  (name %s)\n\
      \  (deps\n\
      \     stdlib.cma stdlib.cmxa stdlib.a\n\
      \     std_exit.cmo std_exit.o std_exit.cmx\n\
      \     (glob_files *.{mli,cmi,cmti,cmsi,cmo,cms,cmt,cmx})\n\
      \     (glob_files caml/*.{h,tbl})\n\
      \     Makefile.config runtime-launch-info ld.conf\n\
      \     dynlink/dynlink.cmxa))\n"
      alias_name
  end

let write_stdlib_jsir_sources_dune ppf =
  setting "stdlib_modules" @ ["std_exit"] |> List.iter (fun m ->
    ["ml"; "mli"] |> List.iter (fun ext ->
      let file = m ^ "." ^ ext in
      fprintf ppf
        "(rule (target %s) (action (copy %%{ocaml_where}/%s %%{target})))\n"
        file file))

type jsir_target =
  { program : string; (* the value of -target *)
    env_var : string; (* where ocamlopt finds [program] *)
    ext_suffix : string }

let jsir_targets =
  [ { program = "js_of_ocaml"; env_var = "OXCAML_JS_OF_OCAML";
      ext_suffix = "js" };
    { program = "wasm_of_ocaml"; env_var = "OXCAML_WASM_OF_OCAML";
      ext_suffix = "wasm" } ]

let write_stdlib_jsir_dune_for_target ppf jsir_target =
  let src_dir = "../src" and stdlib_dir = "../../stdlib" in
  let ext base = base ^ "-" ^ jsir_target.ext_suffix in
  let run_ocamlopt args =
    sprintf "(setenv %s %%{bin:%s} (run %%{ocamlopt} -target %s %s))"
      jsir_target.env_var jsir_target.program jsir_target.program args
  in
  let installed file = sprintf "%%{ocaml_where}/%s" file in
  let table = module_deps_table Sys.argv.(3) in
  iter_module_deps table (fun ~tgt_file ~base ~deps ->
    if Filename.extension tgt_file = ".cmx" then begin
      let target = get_target base in
      let src = sprintf "%s/%s.ml" src_dir base in
      let deps =
        installed (target ^ ".cmi")
        :: List.map (fun dep ->
             match Filename.extension dep with
             | ".cmx" -> Filename.remove_extension dep ^ "." ^ ext "cmx"
             | ".cmi" -> installed dep
             | s -> failwith ("Unexpected extension " ^ s))
             deps
        |> StrSet.of_list |> StrSet.to_list
      in
      (* -S keeps the JSIR of the unit (.cm-jsir-js or .cm-jsir-wasm), with
         which it can also be linked with -link-jsir. *)
      let action =
        run_ocamlopt
          (sprintf
             "%s%s -S -I %%{ocaml_where} -cmi-file %s -o %s.%s -c %%{src}"
             stdlib_flags (pp_flags ~awk_dir:stdlib_dir ~target)
             (installed (target ^ ".cmi")) target (ext "cmx"))
      in
      rule ~ppf ~target ~exts:[ext "cmx"; ext "cmo"; ext "cm-jsir"] ~src ~deps
        ~action
    end);
  let modnames = setting "stdlib_modules" in
  let targets = List.map get_target modnames in
  (* The library is created twice: for separate compilation (.cma-js or
     .cma-wasm) and for -link-jsir (.cma-jsir-js or .cma-jsir-wasm, from the
     JSIR of the units). Both write the same .cmxa-js or .cmxa-wasm. *)
  let action =
    let archive flags =
      targets
      |> List.map (fun t -> sprintf "%%{dep:%s.%s}" t (ext "cmx"))
      |> String.concat " "
      |> sprintf "-g -nostdlib%s -a -o stdlib.%s %s" flags (ext "cmxa")
      |> run_ocamlopt
    in
    sprintf "(progn %s %s)" (archive "") (archive " -link-jsir")
  in
  rule ~ppf ~target:"stdlib" ~exts:[ext "cmxa"; ext "cma"; ext "cma-jsir"]
    ~src:(sprintf "%s/stdlib.ml" src_dir)
    ~deps:
      (List.concat_map
         (fun t -> [t ^ "." ^ ext "cmo"; t ^ "." ^ ext "cm-jsir"])
         targets)
    ~action

let write_stdlib_jsir_dune ppf =
  List.iter (write_stdlib_jsir_dune_for_target ppf) jsir_targets

(* Generate runtime.dune for the main build, which only needs 'primitives' *)
let write_primitives_dune ppf =
  let prim_files =
    setting "runtime_sources.byte" |> List.map Filename.basename in
  fprintf ppf
    "(rule \n\
    \ (target primitives)\n\
