#syntax quotations on

(* Regression test: the stub generated by Simplify for a direct partial
   application must record its *symbol* dependencies in
   [free_names_of_params_and_body]. The stub's body contains the full
   application of the (statically-allocated) callee, referenced by symbol
   and deliberately not stored in a value slot of the wrapper closure; if
   the symbol is stripped from the recorded free names, the callee's
   static closure block gets no [Code_block] dependency edge and the GC
   can reclaim it individually while the stub is still callable.

   [add] below is a known-arity toplevel function of the eval'd unit, so
   Simplify lifts it to a static set of closures and compiles [add 1] as
   a direct partial application (wrapper closure + stub). We hold only
   the partial application across major GCs, then complete it; without
   the dependency edge the full application inside the stub loads a
   freed closure block. *)

let report label =
  let r = Eval.unloadable_units_registered_total () in
  let u = Eval.unloadable_units_unloaded_total () in
  Printf.printf "%s: registered=%d unloaded=%d live=%d\n"
    label r u (r - u)

let partial : (int -> int -> int) ref = ref (fun _ _ -> 0)

let[@inline never] setup () =
  partial
    := Eval.eval
         <[ let add a b c = (a * 100) + (b * 10) + c in
            add 1 ]>

let () =
  report "start";
  setup ();
  (* Only the partial application survives; the callee's static closure
     is referenced solely from the stub's code. *)
  Gc.compact ();
  Gc.compact ();
  report "after compact (partial held; unit must NOT unload)";
  (* Completing the application runs the stub's full application, which
     loads the callee's static closure block. *)
  Printf.printf "completed: %d\n" (!partial 2 3);
  (* Release and confirm the unit unloads. *)
  partial := (fun _ _ -> 0);
  Gc.compact ();
  report "after release + compact"
