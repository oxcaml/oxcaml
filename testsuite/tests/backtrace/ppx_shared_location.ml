open Ast_mapper
open Parsetree

(* Rewrites [[%shared_loc e]] to [e], with every location in [e] replaced by
   the location of the first [[%shared_loc]] payload, like the code generated by
   ppx derivers. *)
let () =
  register "shared_loc" (fun _ ->
    let shared_loc = ref None in
    let expr mapper e =
      match e.pexp_desc with
      | Pexp_extension
          ({ txt = "shared_loc"; _ },
           PStr [{ pstr_desc = Pstr_eval (payload, _); _ }]) ->
        let loc =
          match !shared_loc with
          | Some loc -> loc
          | None ->
            shared_loc := Some payload.pexp_loc;
            payload.pexp_loc
        in
        let set_loc = { default_mapper with location = (fun _ _ -> loc) } in
        set_loc.expr set_loc payload
      | _ -> default_mapper.expr mapper e
    in
    { default_mapper with expr })
